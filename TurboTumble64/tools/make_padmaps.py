#!/usr/bin/env python3
"""make_padmaps.py - writes assets/gamecontrollerdb_easysmx.txt, the extra SDL-format mappings
TurboTumble64 loads after assets/gamecontrollerdb.txt (later lines win).

Covers EasySMX pads (ESM-9101, ESM-9013, ESM-9110) in their three modes and the vendor IDs
they show up under. Mappings use the same button layout as the matching entries in the
official SDL_GameControllerDB. They were NOT checked against a physical pad; if one is wrong,
the in-game remap (Options > Controls) and the raw-joystick fallback still work.

    XInput mode  (LED 1-4, default)  045e:028e  -> already in the main DB (Xbox 360 layout);
                 receiver IDs 2f24:0091 / 2f24:00b7 when the xpad driver binds them on Linux
    DInput mode  ("PC" / LED steady) 20bc:9100, 11c1:9101, 2f24:00b7 (Windows)
    Android mode (Linux fallback)    0079:181c "SHANWAN Android Gamepad", 2563:0575/0526/0527
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "assets", "gamecontrollerdb_easysmx.txt")

def le(v): return "%02x%02x" % (v & 0xff, v >> 8)
def guid_win(vid, pid): return "03000000" + le(vid) + "0000" + le(pid) + "000000000000"
def guid_lin(vid, pid, ver): return "03000000" + le(vid) + "0000" + le(pid) + "0000" + le(ver) + "0000"

HAT = "dpdown:h0.4,dpleft:h0.8,dpright:h0.2,dpup:h0.1"
XBOX_LINUX = "a:b0,b:b1,x:b2,y:b3,back:b6,start:b7,guide:b8,leftshoulder:b4,rightshoulder:b5,leftstick:b9,rightstick:b10,lefttrigger:a2,righttrigger:a5,leftx:a0,lefty:a1,rightx:a3,righty:a4," + HAT
XBOX_WIN = "a:b0,b:b1,x:b2,y:b3,back:b6,start:b7,leftshoulder:b4,rightshoulder:b5,leftstick:b8,rightstick:b9,lefttrigger:a2,righttrigger:a5,leftx:a0,lefty:a1,rightx:a3,righty:a4," + HAT
# PC/DirectInput layout used by EasySMX "D-input" mode and most ShanWan PC pads (0=Y, 1=B, 2=A, 3=X)
DINPUT = "a:b2,b:b1,x:b3,y:b0,back:b8,start:b9,leftshoulder:b4,rightshoulder:b5,lefttrigger:b6,righttrigger:b7,leftstick:b10,rightstick:b11,leftx:a0,lefty:a1,rightx:a2,righty:a3," + HAT
DINPUT_WIN = DINPUT
# Android-mode layout (ShanWan / DragonRise HID gamepad)
ANDROID_LINUX = "a:b0,b:b1,x:b3,y:b4,leftshoulder:b6,rightshoulder:b7,lefttrigger:a5,righttrigger:a4,back:b10,start:b11,guide:b12,leftstick:b13,rightstick:b14,leftx:a0,lefty:a1,rightx:a2,righty:a3," + HAT
ANDROID_WIN = "a:b0,b:b1,x:b3,y:b4,leftshoulder:b6,rightshoulder:b7,lefttrigger:b8,righttrigger:b9,back:b10,start:b11,guide:b12,leftstick:b13,rightstick:b14,leftx:a0,lefty:a1,rightx:a2,righty:a5," + HAT

LIN_VERS = (0x0100, 0x0101, 0x0110, 0x0111)
rows = []
# community-verified entries already in the main DB are kept (we only fill the gaps)
MAIN = set()
for line in open(os.path.join(HERE, "..", "assets", "gamecontrollerdb.txt")):
    if line[:1] in "0123456789abcdef" and "platform:" in line:
        MAIN.add((line.split(",")[0], line.split("platform:")[1].split(",")[0].strip()))
skipped = 0
def add(guid, name, m, plat):
    global skipped
    if (guid, plat) in MAIN: skipped += 1; return
    rows.append("%s,%s,%s,platform:%s," % (guid, name, m, plat))

# XInput receivers that the Linux xpad driver binds (Windows sees them through XInput itself)
for pid, nm in ((0x0091, "EasySMX ESM-9101 (X-input)"), (0x00b7, "EasySMX ESM-9110 (X-input)"), (0x0048, "EasySMX ESM-9013 (X-input)")):
    for v in LIN_VERS: add(guid_lin(0x2f24, pid, v), nm, XBOX_LINUX, "Linux")
add(guid_win(0x2f24, 0x0091), "EasySMX ESM-9101", XBOX_WIN, "Windows")
add(guid_win(0x2f24, 0x0048), "EasySMX ESM-9013", XBOX_WIN, "Windows")
# D-input mode
for vid, pid, nm in ((0x20bc, 0x9100, "EasySMX ESM-9100/9101 (D-input)"), (0x11c1, 0x9101, "EasySMX ESM-9101 (D-input)"),
                     (0x20bc, 0x9013, "EasySMX ESM-9013 (D-input)"), (0x20bc, 0x9110, "EasySMX ESM-9110 (D-input)")):
    add(guid_win(vid, pid), nm, DINPUT_WIN, "Windows")
    for v in LIN_VERS: add(guid_lin(vid, pid, v), nm, DINPUT, "Linux")
# Android mode
for vid, pid, nm in ((0x0079, 0x181c, "EasySMX / SHANWAN Android Gamepad"), (0x2563, 0x0526, "EasySMX / SHANWAN Android Gamepad"),
                     (0x2563, 0x0527, "EasySMX / SHANWAN Android Gamepad")):
    add(guid_win(vid, pid), nm, ANDROID_WIN, "Windows")
    for v in LIN_VERS: add(guid_lin(vid, pid, v), nm, ANDROID_LINUX, "Linux")

hdr = ["# TurboTumble64 extra controller mappings (SDL GameControllerDB format).",
       "# Loaded after gamecontrollerdb.txt; a GUID here replaces the one there.",
       "# Generated by tools/make_padmaps.py - EasySMX ESM-9101 / ESM-9013 / ESM-9110 in X-input,",
       "# D-input and Android modes. Unknown pads fall back to the raw joystick reader (Pad mode AUTO/RAW)",
       "# and every action can be remapped in Options > Controls."]
# sanity: SDL format + no duplicate GUID/platform
seen = set()
for r in rows:
    g = r.split(",")[0]; plat = r.rstrip(",").split("platform:")[1]
    assert len(g) == 32 and all(c in "0123456789abcdef" for c in g), g
    assert (g, plat) not in seen, g; seen.add((g, plat))
open(OUT, "w").write("\n".join(hdr + rows) + "\n")
print("wrote", OUT, len(rows), "mappings,", skipped, "already in the main DB")
