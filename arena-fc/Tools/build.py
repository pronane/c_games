#!/usr/bin/env python3
"""
Arena FC - cross-platform build / export tool.

    python Tools/build.py --platforms all
    python Tools/build.py --platforms web
    python Tools/build.py --platforms windows linux --out build
    python Tools/build.py --check          # run unit + in-engine self tests
    python Tools/build.py --run            # boot the game with the local editor
    python Tools/build.py --serve          # serve the web build locally

It bootstraps its own toolchain when needed (Godot 4.7.2 .NET editor, standard
editor, .NET 9 SDK and matching export templates) into ~/.cache/arena-fc, then
produces installable packages for every supported device family.

Why two editors?  Godot 4 cannot export C#/.NET projects to the Web.  The
`web` target therefore builds a GDScript-only copy (Web/BrowserBoot.gd) which
loads the SAME skinned rig data (Data/rig_default.json) generated by the C#
RigBuilder.  See README.md for the honest platform matrix.
"""
from __future__ import annotations
import argparse
import json
import os
import platform as _platform
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
import zipfile
from pathlib import Path

VERSION = "4.7.2"
TAG = f"{VERSION}-stable"
ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(os.environ.get("ARENA_FC_CACHE", Path.home() / ".cache" / "arena-fc"))
OUT = ROOT / "build"
GITHUB = f"https://github.com/godotengine/godot/releases/download/{TAG}"

NATIVE = {
    "windows": ("Windows Desktop", "windows/ArenaFC.exe"),
    "linux":   ("Linux",           "linux/ArenaFC.x86_64"),
    "macos":   ("macOS",           "macos/ArenaFC.zip"),
    "android": ("Android",         "android/ArenaFC.apk"),
    "ios":     ("iOS",             "ios/ArenaFC.ipa"),
}
ALL = list(NATIVE) + ["web"]


def log(msg=""): print(msg, flush=True)
def warn(msg): print(f"  ! {msg}", flush=True)
def die(msg): print(f"ERROR: {msg}", flush=True); sys.exit(1)


def system() -> str:
    if sys.platform.startswith("win"): return "windows"
    if sys.platform == "darwin": return "macos"
    return "linux"


def download(url: str, dest: Path) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and dest.stat().st_size > 1000:
        return dest
    tmp = dest.with_suffix(dest.suffix + ".part")
    log(f"  downloading {url}")
    urllib.request.urlretrieve(url, tmp)
    tmp.replace(dest)
    return dest


def unzip(archive: Path, dest: Path):
    dest.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        z.extractall(dest)


def find_binary(folder: Path, needle: str) -> Path | None:
    if not folder.exists(): return None
    for p in folder.rglob("*"):
        if p.is_file() and needle in p.name and not p.name.endswith((".pdb", ".xml", ".dll")):
            return p
    return None


def godot_version(exe: Path) -> str:
    out = subprocess.run([str(exe), "--headless", "--version"], capture_output=True, text=True, timeout=60)
    return (out.stdout or out.stderr).strip()


def ensure_editor(mono: bool, override: str | None) -> Path:
    if override: return Path(override)
    key = "mono" if mono else "std"
    env = os.environ.get("GODOT_MONO" if mono else "GODOT_STANDARD")
    if env: return Path(env)
    found = find_binary(CACHE / key, "Godot_v")
    if found and os.access(found, 0o111): return found
    for name in ("godot", "godot4", "Godot"):
        which = shutil.which(name)
        if which:
            v = godot_version(Path(which))
            if ("mono" in v) == mono: return Path(which)
    sysname = system()
    if sysname == "linux":
        fname = f"Godot_v{TAG}_mono_linux_x86_64.zip" if mono else f"Godot_v{TAG}_linux.x86_64.zip"
    elif sysname == "windows":
        fname = f"Godot_v{TAG}_mono_win64.zip" if mono else f"Godot_v{TAG}_win64.exe.zip"
    else:
        fname = f"Godot_v{TAG}_mono_macos.universal.zip" if mono else f"Godot_v{TAG}_macos.universal.zip"
    archive = download(f"{GITHUB}/{fname}", CACHE / fname)
    unzip(archive, CACHE / key)
    exe = find_binary(CACHE / key, "Godot_v")
    if not exe: die(f"Could not find the Godot binary inside {archive}")
    exe.chmod(exe.stat().st_mode | 0o111)
    return exe


def ensure_dotnet() -> str:
    found = shutil.which("dotnet")
    if found:
        r = subprocess.run([found, "--list-sdks"], capture_output=True, text=True)
        if "9." in (r.stdout or ""): return found
        warn("dotnet found but no .NET 9 SDK; Godot 4.7 C# Android export needs .NET 9.")
    local = CACHE / "dotnet" / ("dotnet.exe" if system() == "windows" else "dotnet")
    if local.exists():
        os.environ["DOTNET_ROOT"] = str(local.parent)
        return str(local)
    script = CACHE / "dotnet-install.sh"
    if system() != "windows":
        download("https://dot.net/v1/dotnet-install.sh", script)
        subprocess.run(["bash", str(script), "--channel", "9.0", "--install-dir", str(CACHE / "dotnet"), "--no-path"], check=True)
    else:
        ps = CACHE / "dotnet-install.ps1"
        download("https://dot.net/v1/dotnet-install.ps1", ps)
        subprocess.run(["powershell", "-File", str(ps), "-Channel", "9.0", "-InstallDir", str(CACHE / "dotnet"), "-NoPath"], check=True)
    os.environ["DOTNET_ROOT"] = str(CACHE / "dotnet")
    return str(local)


def templates_dir() -> Path:
    if system() == "windows":
        base = Path(os.environ.get("APPDATA", Path.home())) / "Godot"
    elif system() == "macos":
        base = Path.home() / "Library" / "Application Support" / "Godot"
    else:
        base = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "godot"
    return base / "export_templates"


def ensure_templates(mono: bool):
    version = f"{VERSION}.stable.mono" if mono else f"{VERSION}.stable"
    dest = templates_dir() / version
    if (dest / "version.txt").exists(): return version
    name = f"Godot_v{TAG}_mono_export_templates.tpz" if mono else f"Godot_v{TAG}_export_templates.tpz"
    archive = download(f"{GITHUB}/{name}", CACHE / name)
    dest.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        for member in z.namelist():
            if member.startswith("templates/") and not member.endswith("/"):
                (dest / Path(member).name).write_bytes(z.read(member))
    (dest / "version.txt").write_text(version + "\n")
    log(f"  installed export templates -> {dest}")
    return version


def configure_android(sdk: str | None, java: str | None, keystore: str | None):
    """Point Godot's EditorSettings at a local Android SDK / JDK (optional)."""
    if not sdk and not java and not keystore: return
    if system() == "windows":
        base = Path(os.environ.get("APPDATA", Path.home())) / "Godot"
    elif system() == "macos":
        base = Path.home() / "Library" / "Application Support" / "Godot"
    else:
        base = Path.home() / ".config" / "godot"
    f = base / "editor_settings-4.7.tres"
    if f.exists():
        text = f.read_text(encoding="utf-8", errors="replace")
    else:
        text = '[gd_resource type="EditorSettings" format=3]\n\n[resource]\n'
    def setkey(key, value):
        nonlocal text
        pat = re.compile(rf'^{re.escape(key)} = .*$', re.M)
        line = f'{key} = "{value}"'
        if pat.search(text): text = pat.sub(lambda _: line, text)
        else: text += line + "\n"
    if sdk: setkey("export/android/android_sdk_path", sdk)
    if java: setkey("export/android/java_sdk_path", java)
    if keystore:
        setkey("export/android/debug_keystore", keystore)
        setkey("export/android/debug_keystore_pass", "android")
    if "[resource]" not in text: text += "\n[resource]\n"
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8")
    log(f"  configured Android SDK in {f}")


def cleanup_temp():
    """Godot leaves large staging folders in the OS temp dir after an aborted
    export.  On small machines those consume RAM (tmpfs) and cause OOM kills."""
    tmp = Path(tempfile.gettempdir())
    for name in ("Arena FC", "godot-publish-dotnet", "_lipo"):
        p = tmp / name
        if p.exists(): shutil.rmtree(p, ignore_errors=True)
    for p in tmp.glob("tmpexport-unaligned*.apk"):
        try: p.unlink()
        except OSError: pass


def run(cmd: list[str], cwd: Path | None = None, env: dict | None = None, timeout=300, retry=0) -> int:
    cleanup_temp()
    log("  $ " + " ".join(str(c) for c in cmd))
    e = os.environ.copy()
    if env: e.update(env)
    rc = -1
    for attempt in range(retry + 1):
        try:
            r = subprocess.run([str(c) for c in cmd], cwd=str(cwd or ROOT), env=e, timeout=timeout)
            rc = r.returncode
        except subprocess.TimeoutExpired:
            rc = 124
        if rc == 0 or rc == 124:
            return rc
        if rc in (-9, -11) and attempt < retry:
            warn(f"exporter was killed by the OS (code {rc}); waiting and retrying once …")
            cleanup_temp()
            time.sleep(5)
            continue
        return rc
    return rc


def build_cs() -> bool:
    dotnet = ensure_dotnet()
    os.environ["DOTNET_ROOT"] = str(Path(dotnet).parent)
    os.environ["PATH"] = str(Path(dotnet).parent) + os.pathsep + os.environ.get("PATH", "")
    log("\n[1/5] Building C# assemblies with .NET 9 …")
    rc = run([dotnet, "build", str(ROOT / "ArenaFC.sln"), "-c", "Release", "-v:q"])
    if rc != 0: die("C# build failed. See errors above.")
    return True


def run_checks():
    build_cs()
    dotnet = shutil.which("dotnet") or str(CACHE / "dotnet" / "dotnet")
    mono = ensure_editor(True, None)
    log("\n[2/5] Pure-C# unit tests …")
    if run([dotnet, "run", "--project", str(ROOT / "Tests/CoreTests.csproj"), "-c", "Release"]) != 0:
        die("Core tests failed.")
    log("\n[3/5] In-engine Godot self test …")
    if run([mono, "--headless", "--path", str(ROOT), "--rendering-driver", "dummy",
            "--audio-driver", "Dummy", "--", "--selftest"], timeout=300) != 0:
        die("Godot self test failed.")
    log("\n[4/5] v2 network integration (reconnect / migration / rollback) …")
    server_bin = ROOT / "Server/bin/Release/net9.0/ArenaFC.Server.dll"
    if not server_bin.exists():
        warn("Server not built; skipping network tests. Run: dotnet build Server/ArenaFC.Server.csproj -c Release")
    else:
        import subprocess as _sp
        port = 17777
        proc = _sp.Popen([dotnet, str(server_bin), "--port", str(port), "--bind", "127.0.0.1",
                          "--peer-host", "--grace-seconds", "180"],
                         stdout=_sp.DEVNULL, stderr=_sp.DEVNULL)
        try:
            import time as _time
            for _ in range(40):
                _time.sleep(.25)
                try:
                    import urllib.request as _u
                    with _u.urlopen(f"http://127.0.0.1:{port}/health", timeout=2) as _r:
                        if _r.status == 200: break
                except Exception: pass
            url = f"ws://127.0.0.1:{port}"
            py = sys.executable
            for script in ("net_smoketest.py", "net_v2_smoketest.py"):
                if run([py, str(ROOT / "Tools" / script), "--url", url, "--seconds", "2.5"], timeout=180) != 0:
                    die(f"{script} failed.")
            log("\n[5/5] ALL CHECKS PASSED (88 core + 47 in-engine + 17 classic network + 36 v2 network assertions).")
        finally:
            proc.terminate()
            try: proc.wait(timeout=5)
            except Exception: proc.kill()


def make_web_source(web_src: Path):
    if web_src.exists(): shutil.rmtree(web_src)
    web_src.mkdir(parents=True)
    keep_dirs = ["Shaders", "Data", "Web", "Assets"]
    for d in keep_dirs:
        src = ROOT / d
        if src.exists(): shutil.copytree(src, web_src / d, ignore=shutil.ignore_patterns("*.import"))
    shutil.copy2(ROOT / "icon.svg", web_src / "icon.svg")
    # project.godot without the .NET section, pointing at the GDScript entry point.
    cfg = (ROOT / "project.godot").read_text()
    cfg = cfg.replace('run/main_scene="res://Scenes/Main.tscn"', 'run/main_scene="res://Web/BrowserMain.tscn"')
    cfg = re.sub(r'\n\[dotnet\]\n(?:.*\n)*?(?=\n\[|\Z)', '\n', cfg)
    cfg = cfg.replace('config/name="Arena FC"', 'config/name="Arena FC Browser Edition"')
    cfg = cfg.replace(', "C#"', '')
    (web_src / "project.godot").write_text(cfg)
    shutil.copy2(ROOT / "Web/export_presets_web.cfg", web_src / "export_presets.cfg")
    # Sanity: no C# left in the web project.
    leftovers = list(web_src.rglob("*.cs"))
    if leftovers: die(f"Web variant still has C# files: {leftovers}")
    log(f"  generated GDScript-only web project at {web_src}")


def export_web(std: Path, out: Path, results: dict):
    log("\n--- Web / HTML5 (GDScript Browser Edition) ---")
    web_src = out / "web_src"
    make_web_source(web_src)
    target = out / "web" / "index.html"
    target.parent.mkdir(parents=True, exist_ok=True)
    rc = run([std, "--headless", "--path", str(web_src), "--export-release", "Web", str(target)], timeout=300, retry=2)
    if rc == 0 and target.exists():
        size = sum(f.stat().st_size for f in target.parent.iterdir() if f.is_file())
        results["web"] = {"path": str(target), "bytes": size, "status": "ok",
                          "note": "GDScript Browser Edition (Godot cannot export C# to Web)."}
        log(f"  OK  {target}  ({size/1e6:.1f} MB total)")
        shutil.copy2(ROOT / "Tools/serve_web.py", target.parent / "serve.py")
    else:
        results["web"] = {"status": "failed", "note": "Web export failed"}
        warn("Web export failed. Check the log above.")


def main():
    ap = argparse.ArgumentParser(description="Arena FC cross-platform build tool")
    ap.add_argument("--platforms", default="all", help="comma list: windows,linux,macos,android,ios,web,all")
    ap.add_argument("--out", default=str(OUT), help="output directory")
    ap.add_argument("--godot-mono", help="path to the .NET Godot editor")
    ap.add_argument("--godot-standard", help="path to the standard Godot editor")
    ap.add_argument("--android-sdk", default=os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT"))
    ap.add_argument("--java-home", default=os.environ.get("JAVA_HOME"))
    ap.add_argument("--android-keystore", default=None, help="debug keystore for signing APKs")
    ap.add_argument("--check", action="store_true", help="run test suites and exit")
    ap.add_argument("--run", action="store_true", help="launch the game locally")
    ap.add_argument("--serve", action="store_true", help="serve the web build")
    ap.add_argument("--no-bootstrap", action="store_true", help="do not download missing toolchain parts")
    args = ap.parse_args()

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    if args.check: run_checks(); return
    if args.serve:
        web = out / "web"
        if not (web / "index.html").exists(): die("No web build yet. Run: python Tools/build.py --platforms web")
        os.chdir(web)
        import runpy
        sys.argv = ["serve.py", "--port", "8080"]
        runpy.run_path(str(web / "serve.py"), run_name="__main__")
        return

    wanted = ALL if args.platforms.strip().lower() == "all" else [p.strip().lower() for p in args.platforms.split(",") if p.strip()]
    unknown = [p for p in wanted if p not in ALL]
    if unknown: die(f"Unknown platform(s): {unknown}. Choose from {ALL}")
    # Web's WASM link is memory-hungry: do it first, before the native exporters
    # have filled the page cache, on machines with limited RAM.
    wanted.sort(key=lambda p: 0 if p == "web" else 1)

    build_cs()
    mono = ensure_editor(True, args.godot_mono)
    std = ensure_editor(False, args.godot_standard) if "web" in wanted else None
    log(f"  Godot .NET editor : {mono}  [{godot_version(mono)}]")
    if std: log(f"  Godot std editor  : {std}  [{godot_version(std)}]")
    ensure_templates(True)
    if "web" in wanted: ensure_templates(False)
    configure_android(args.android_sdk, args.java_home, args.android_keystore)

    if args.run:
        log("\nLaunching Arena FC …")
        run([mono, "--path", str(ROOT)], timeout=100000)
        return

    results: dict = {}
    for p in wanted:
        if p == "web":
            if std: export_web(std, out, results)
            continue
        preset, rel = NATIVE[p]
        log(f"\n--- {preset} ---")
        if p == "ios" and system() != "macos":
            msg = ("Godot 4.7 refuses to export C#/.NET to Apple Embedded platforms outside macOS "
                   "(needs Xcode for signing). Run this script on a Mac with Xcode.")
            warn(msg)
            results[p] = {"status": "skipped", "note": msg}
            continue
        if p == "android" and not args.android_sdk:
            warn("No Android SDK detected (--android-sdk / ANDROID_HOME). Attempting anyway …")
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        rc = run([mono, "--headless", "--path", str(ROOT), "--export-release", preset, str(target)], retry=1)
        ok = rc == 0 and target.exists()
        if ok:
            results[p] = {"path": str(target), "bytes": target.stat().st_size, "status": "ok", "preset": preset}
            log(f"  OK  {target}  ({target.stat().st_size/1e6:.1f} MB)")
        else:
            results[p] = {"status": "failed", "preset": preset, "note": "see console output above"}
            warn(f"Export for {preset} failed (exit {rc}).")

    manifest_path = out / "MANIFEST.json"
    merged: dict = {}
    if manifest_path.exists():
        try: merged = json.loads(manifest_path.read_text()).get("platforms", {})
        except Exception: merged = {}
    merged.update(results)
    manifest_path.write_text(json.dumps({
        "game": "Arena FC", "engine": "Godot 4.7.2", "language": "C#/.NET 9 (+ GDScript web fallback)",
        "generated_by": "Tools/build.py", "platforms": merged,
    }, indent=2))
    log("\n================ BUILD SUMMARY ================")
    for k, v in results.items():
        log(f"  {k:<9} {v['status']:<8} {v.get('path','')}")
    log(f"\nManifest: {out / 'MANIFEST.json'}")
    log("Tip: python Tools/build.py --serve   (play the web build locally)")


if __name__ == "__main__":
    try: main()
    except KeyboardInterrupt: sys.exit(130)
