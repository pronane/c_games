// Visual corrections / portable source / progress UI. Synthetic fixture; no model accuracy claim.
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE_PATH ?? '/tmp/chromium', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(String(e)));
  await page.goto(process.env.STUDIO_URL ?? 'http://127.0.0.1:5173');
  const studio = page.locator('#practice-studio');
  const report = { source: 'file', label: 'Reference', summary: { overall: 90, pitch_accuracy: .9, timing_accuracy: 1, completeness: 1 }, notes: [{ id: 0, bar: 1, beat: 1, kind: 'wrong_pitch', message: 'Wrong pitch', target_time: 1, take_time: 1 }], bars: [], worst_bars: [] };
  const attempts = [1,2].map(i => ({ id: `take${i}`, created: i, revision: 1, start: 0, end: 4, speed: .7, reviews: i === 1 ? { '1:0:wrong_pitch': 'confirmed' } : {}, latencyMeasured: true, comparison: { reports: [report], combined: null } }));
  const p = { version: 1, id: 'visual-fixture', title: 'Visual chord fixture', part: 'Rhythm guitar', tuning: 'standard', capo: 0, bpm: 120, duration: 6, notes: [{ time: 1, duration: .5, midi: 60 }, { time: 1.02, duration: .5, midi: 64 }, { time: 2, duration: .5, midi: 67 }], origin: 'chart', revision: 1, practiceSpeed: .7, activeSection: 'chorus', goal: 'Chord transition', trust: 'reviewed', sections: [{ id: 'chorus', name: 'Chorus', start: 0, end: 4 }], ignored: [], attempts, updated: Date.now() };
  const upload = studio.locator('input[accept=".json"]');
  await upload.setInputFiles({ name: 'visual.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(p)) });
  await studio.getByText('Imported as an unsaved copy.').waitFor();
  await studio.getByText('Review both takes first;', { exact: false }).waitFor();
  await studio.getByLabel('Review finding 0', { exact: true }).selectOption('dismissed');
  await studio.getByText('Fewer human-confirmed findings on this retry.', { exact: false }).waitFor();
  assert.equal(await studio.getByRole('table', { name: 'Comparable phrase take history' }).locator('tbody tr').count(), 2);
  await studio.getByText('Visual reference editor — notes and chord tones', { exact: true }).click();
  const visual = studio.locator('.visual-editor');
  await visual.getByLabel('Select chord tones together', { exact: false }).check();
  await visual.getByRole('button', { name: /^Note 1:/ }).click();
  await visual.getByText('2 note(s) selected.', { exact: false }).waitFor();
  await visual.getByRole('button', { name: 'Transpose selection up', exact: true }).click();
  assert.equal(await visual.getByLabel('Selected MIDI pitch').inputValue(), '61');
  assert.equal(await studio.getByLabel('I reviewed this reference', { exact: false }).isChecked(), true, 'draft does not change approval');
  await visual.getByRole('button', { name: 'Undo note edit', exact: true }).click();
  await visual.getByRole('button', { name: /^Note 1: C4/ }).waitFor();
  await visual.getByRole('button', { name: 'Redo note edit', exact: true }).click();
  await visual.getByRole('button', { name: /^Note 1: C♯4/ }).waitFor();
  await visual.getByLabel('Select chord tones together', { exact: false }).uncheck();
  const note = visual.getByRole('button', { name: /^Note 3:/ });
  await note.click(); await note.press('ArrowUp'); await note.press('ArrowRight');
  assert.equal(await visual.getByLabel('Selected MIDI pitch').inputValue(), '68');
  assert.equal(Number(await visual.getByLabel('Selected start seconds').inputValue()), 2.125);
  await visual.getByLabel('Selected length seconds').fill('0.75');
  assert.equal(Number(await visual.getByLabel('Selected length seconds').inputValue()), .75);
  await visual.getByRole('button', { name: 'Add E4 at section start', exact: true }).click();
  assert.equal(await visual.getByRole('button', { name: /^Note [0-9]+:/ }).count(), 4);
  await visual.getByRole('button', { name: 'Delete selected notes', exact: true }).click();
  assert.equal(await visual.getByRole('button', { name: /^Note [0-9]+:/ }).count(), 3);
  // Pointer drag: one beat later, one semitone higher. Snap remains 1/16.
  await note.scrollIntoViewIfNeeded(); const box = await note.boundingBox();
  await page.mouse.move(box.x + 10, box.y + 5); await page.mouse.down();
  await page.mouse.move(box.x + 60, box.y - 13, { steps: 5 }); await page.mouse.up();
  assert.equal(await visual.getByLabel('Selected MIDI pitch').inputValue(), '69');
  assert.equal(Number(await visual.getByLabel('Selected start seconds').inputValue()), 2.625);
  await visual.getByRole('button', { name: 'Audition draft phrase', exact: true }).click();
  await studio.getByRole('button', { name: 'Stop phrase playback', exact: true }).click();
  await visual.getByRole('button', { name: 'Apply visual corrections', exact: true }).click();
  await studio.getByText('Reference corrected.', { exact: false }).waitFor();
  assert.equal(await studio.getByLabel('I reviewed this reference', { exact: false }).isChecked(), false);
  await studio.getByText('Reference changed.', { exact: false }).waitFor();
  await studio.getByText('Keep an original reference chart with this project', { exact: true }).click();
  const chart = '<score-partwise version="4.0"><work><work-title>Original</work-title></work></score-partwise>';
  await studio.getByLabel('Attach original chart').setInputFiles({ name: 'original.musicxml', mimeType: 'text/xml', buffer: Buffer.from(chart) });
  await studio.getByText('Original reference chart attached.', { exact: false }).waitFor();
  await studio.getByRole('button', { name: 'Save project on this device' }).click();
  await studio.getByText('Saved on this device.', { exact: false }).waitFor();
  const event = page.waitForEvent('download'); await studio.getByRole('button', { name: 'Export project & takes' }).click();
  const download = await event, stream = await download.createReadStream(), chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const bytes = Buffer.concat(chunks), exported = JSON.parse(bytes.toString());
  assert.equal(exported.revision, 2); assert.equal(exported.trust, 'unverified');
  assert.equal(exported.notes[0].midi, 61); assert.equal(exported.notes[1].midi, 65);
  assert.equal(Buffer.from(exported.reference.file.split(',')[1], 'base64').toString(), chart);
  await page.reload();
  await studio.getByLabel('Saved practice projects').selectOption({ label: 'Visual chord fixture (imported)' });
  await studio.getByText('Keep an original reference chart with this project', { exact: true }).click();
  await studio.getByRole('button', { name: 'Download original chart', exact: true }).waitFor();
  await upload.setInputFiles({ name: 'roundtrip.json', mimeType: 'application/json', buffer: bytes });
  await studio.getByText('Imported as an unsaved copy.').waitFor();
  await studio.getByRole('button', { name: 'Save project on this device' }).click();
  await studio.getByText('Saved on this device.', { exact: false }).waitFor();
  assert.equal(await studio.getByLabel('Saved practice projects').locator('option').count(), 3, 'roundtrip import creates a copy');
  assert.deepEqual(errors, []);
  if (process.env.SCREENSHOT_PATH) await studio.screenshot({ path: process.env.SCREENSHOT_PATH });
  console.log('PASS: chord and keyboard selection; bounded transpose/time/length editing; add/delete; pointer drag; undo/redo; draft audition; explicit revision/appraisal reset; historical-take guard; review-coverage-gated progress; original chart save/reload/export/import roundtrip. No browser exceptions. Synthetic workflow only.');
} finally { await browser.close(); }
