"""Build the bundled starter library + packs/sfs_starter_cc0.sfpack (all synthetic, CC0).

    python tools/make_starter_library.py [--library DIR] [--pack OUT] [--no-pack]
Everything here is generated procedurally by this program (no captures, no third-party assets)."""
import argparse, os, sys, time
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from sforge import library as L, rigrec as RR, bonemap as BM, samplerigs as S

KITS = {
    "sample_red_white": dict(description="synthetic sample kit: red shirt, white shorts, red socks",
                             materials={"*shirt*|*jersey*|*top*": {"color": "#c8102e", "mode": "tint"},
                                        "*short*|*pant*": {"color": "#f2f2f2", "mode": "replace"},
                                        "*sock*": {"color": "#c8102e", "mode": "replace"}}),
    "sample_gold_black": dict(description="synthetic sample kit: gold shirt, black shorts and socks",
                              materials={"*shirt*|*jersey*|*top*": {"color": "#e8b923", "mode": "tint"},
                                         "*short*|*pant*": {"color": "#161616", "mode": "replace"},
                                         "*sock*": {"color": "#161616", "mode": "replace"}}),
    "sample_sky_navy": dict(description="synthetic sample kit: sky-blue shirt, navy shorts, white socks",
                            materials={"*shirt*|*jersey*|*top*": {"color": "#6cabdd", "mode": "tint"},
                                       "*short*|*pant*": {"color": "#1c2c5b", "mode": "replace"},
                                       "*sock*": {"color": "#ffffff", "mode": "replace"}}),
}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--library", default=os.path.join(HERE, "library"))
    ap.add_argument("--pack", default=os.path.join(HERE, "packs", "sfs_starter_cc0.sfpack"))
    ap.add_argument("--no-pack", action="store_true")
    a = ap.parse_args(argv)
    lib = L.Library(a.library); lib.ensure()
    t0 = time.time()
    m = RR.from_mannequin("sforge_mannequin", clips=S.STARTER_CLIPS)
    m.meta["description"] = "the built-in no-likeness mannequin (18 bones, rigid parts) with 7 procedural clips"
    mrec = BM.detect(m)
    lib.save_rig(m, mrec, "rigs", dict(S.CC0))
    print("mannequin", round(time.time() - t0, 1), "s")
    for name in S.PRESETS:
        r = S.build(name)
        rec = BM.detect(r)
        BM.orient(r, rec, {})
        S.add_clips(r, rec, mannequin=m)
        lib.save_rig(r, rec, "rigs", dict(S.CC0))
        print(name, rec["convention"], len(r.clips), "clips", round(time.time() - t0, 1), "s")
    r, rec = S.moves_library()
    lib.save_rig(r, rec, "animations", dict(S.CC0))
    for k, v in KITS.items():
        lib.add_kit(k, v, dict(S.CC0))
    man, _ = lib.scan(import_inbox=False)
    print("library:", len(man["assets"]), "assets in", lib.dir)
    if not a.no_pack:
        lib.pack(a.pack, None, "Sprite Forge Studio starter pack (CC0)",
                 "Synthetic rigs, animations and kits generated by Sprite Forge Studio. CC0-1.0: use them for anything.")
        rep = L.verify(a.pack)
        print("pack", a.pack, os.path.getsize(a.pack) // 1024, "KB", "verify ok" if rep["ok"] else rep["problems"])


if __name__ == "__main__":
    main()
