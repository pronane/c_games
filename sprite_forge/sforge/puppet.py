"""v7.1 PHOTO PUPPET: fighting moves from ONE cut-out photo (+ its pose landmarks).

The cut-out is split into pieces with the photo's own pixels - torso+head, upper arm / forearm+hand
(x2), thigh / shin+foot (x2) - using the MediaPipe landmarks from `forge.py cutout`.  Every move is a
list of key poses (segment directions, lean, lift, effects); each frame rotates / moves the pieces about
their joints (shoulder, elbow, hip, knee) and composites them again, feet put back on the ground line.
Where a moved arm used to cover the body, the gap is filled from the nearest body pixels (smoothed).

These are PROCEDURAL poses - a cut-out puppet, not real photographs of the person in those poses.
Nothing is generated by AI and no other character's pixels are used.  Effects (hand glow, energy orb,
hit flash) are drawn procedurally and are not part of the person.

Directions are in degrees from 'pointing straight down': +90 = forward (towards the opponent, image
right), -90 = backwards, 180 = straight up.  'near' = the arm / leg on the image-right side.
"""
from __future__ import annotations
import json, math
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
from scipy import ndimage as ndi

SIDES = {   # mediapipe ids: shoulder, elbow, wrist, hand points, hip, knee, ankle, heel, toe
    "near": dict(S=11, E=13, W=15, H=(17, 19, 21), P=23, K=25, A=27, heel=29, toe=31),
    "far": dict(S=12, E=14, W=16, H=(18, 20, 22), P=24, K=26, A=28, heel=30, toe=32),
}
SEGS = ("un", "fn", "uf", "ff", "tn", "sn", "tf", "sf")     # upper/fore arm, thigh/shin; near/far


def _dir(p, q):
    return math.degrees(math.atan2(q[0] - p[0], q[1] - p[1]))


def _rot(theta, c):
    """3x3 forward matrix: visual counter-clockwise rotation by theta (deg) about c, screen coords"""
    t = math.radians(theta)
    ct, st = math.cos(t), math.sin(t)
    R = np.array([[ct, st, 0], [-st, ct, 0], [0, 0, 1]])
    T = np.array([[1, 0, c[0]], [0, 1, c[1]], [0, 0, 1]])
    Ti = np.array([[1, 0, -c[0]], [0, 1, -c[1]], [0, 0, 1]])
    return T @ R @ Ti


def _tr(dx, dy):
    return np.array([[1, 0, dx], [0, 1, dy], [0, 0, 1.0]])


def _scale(sx, sy, c):
    return _tr(c[0], c[1]) @ np.diag([sx, sy, 1.0]) @ _tr(-c[0], -c[1])


def _ap(M, p):
    v = M @ np.array([p[0], p[1], 1.0])
    return (v[0], v[1])


def _capsule(shape, p0, p1, r):
    h, w = shape
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    vx, vy = p1[0] - p0[0], p1[1] - p0[1]
    L2 = max(1e-6, vx * vx + vy * vy)
    t = np.clip(((xx - p0[0]) * vx + (yy - p0[1]) * vy) / L2, 0, 1)
    return (xx - p0[0] - t * vx) ** 2 + (yy - p0[1] - t * vy) ** 2 <= r * r


def _disc(shape, c, r):
    h, w = shape
    yy, xx = np.mgrid[0:h, 0:w]
    return (xx - c[0]) ** 2 + (yy - c[1]) ** 2 <= r * r


def _poly(shape, pts):
    m = Image.new("L", (shape[1], shape[0]), 0)
    ImageDraw.Draw(m).polygon([tuple(map(float, p)) for p in pts], fill=255)
    return np.asarray(m) > 0


def _fill_from_nearest(rgba, todo, known, blur=6):
    """gap left by a moved limb: nearest known body colour, then smoothed (no new detail invented)"""
    if not todo.any():
        return rgba
    out = rgba.copy()
    _, (iy, ix) = ndi.distance_transform_edt(~known, return_indices=True)
    fill = rgba[iy, ix, :3].astype(np.float32)
    sm = np.stack([ndi.gaussian_filter(fill[..., c], blur) for c in range(3)], -1)
    out[todo, :3] = sm[todo].clip(0, 255).astype(np.uint8)
    out[todo, 3] = 255
    return out


class Rig:
    def __init__(self, cut: Image.Image, landmarks, pad_frac=0.75, colour_ref=None):
        """colour_ref (v9): the photo BEFORE a colour swap - skin / jeans colour tests that decide the rig pieces use
        it, so a recoloured top (e.g. a light-blue variant) cannot change which pixels belong to the arm"""
        a0 = np.asarray(cut.convert("RGBA"))
        h0, w0 = a0.shape[:2]
        self.pad = pad = int(h0 * pad_frac)
        self.padt = padt = int(h0 * 0.45)
        A = np.zeros((h0 + padt + 8, w0 + 2 * pad, 4), np.uint8)
        A[padt:padt + h0, pad:pad + w0] = a0
        self.A = A
        H, W = A.shape[:2]
        L = [(x + pad, y + padt) for x, y, _ in landmarks]
        self.L = L
        alpha = A[..., 3] > 0
        rows = np.nonzero(alpha.any(1))[0]
        self.top, self.ground = int(rows.min()), int(rows.max())
        self.stand_h = self.ground - self.top + 1
        sw = math.hypot(L[11][0] - L[12][0], L[11][1] - L[12][1])
        self.cx = (L[11][0] + L[12][0] + L[23][0] + L[24][0]) / 4.0
        J = {}
        for side, ids in SIDES.items():
            k = side[0]
            hand = tuple(np.mean([L[i] for i in ids["H"]], axis=0))
            W_ = L[ids["W"]]
            tip = (W_[0] + (hand[0] - W_[0]) * 1.9, W_[1] + (hand[1] - W_[1]) * 1.9)
            J[k] = dict(S=L[ids["S"]], E=L[ids["E"]], W=W_, T=tip, P=L[ids["P"]], K=L[ids["K"]], A=L[ids["A"]],
                        toe=L[ids["toe"]], heel=L[ids["heel"]])
        self.J = J
        # crotch: first transparent pixel below the hips between the legs
        mx = int(round((J["n"]["K"][0] + J["f"]["K"][0]) / 2))
        hy = int(max(J["n"]["P"][1], J["f"]["P"][1]))
        col = alpha[:, mx]
        yc = next((y for y in range(hy, H) if not col[y]), int((hy + J["n"]["K"][1]) / 2))
        self.crotch = yc
        ru, rf = 0.165 * sw, 0.145 * sw
        self.r_leg = 0.17 * sw
        yy, xx = np.mgrid[0:H, 0:W]
        # body hull (torso + pelvis) - where a moved arm leaves a gap that must be filled
        m = 0.06 * sw
        hull = _poly(alpha.shape, [(J["f"]["S"][0] - m, J["f"]["S"][1] - 0.1 * sw), (J["n"]["S"][0] + m, J["n"]["S"][1] - 0.1 * sw),
                                    (J["n"]["P"][0] + 2 * m, yc), (J["f"]["P"][0] - 2 * m, yc)])
        # legs below the crotch, split by the seam between the leg centre lines
        def cl(k, y):      # x of leg k's centre line at row y (hip -> knee -> ankle)
            P, K, A_ = J[k]["P"], J[k]["K"], J[k]["A"]
            if y <= K[1]:
                t = (y - P[1]) / max(1, K[1] - P[1]); return P[0] + t * (K[0] - P[0])
            t = (y - K[1]) / max(1, A_[1] - K[1]); return K[0] + t * (A_[0] - K[0])
        seam = np.array([(cl("n", y) + cl("f", y)) / 2 for y in range(H)])
        below = (yy >= yc) & alpha
        near_side = xx >= seam[:, None]
        pieces = {}
        for k, side_mask in (("n", near_side), ("f", ~near_side)):
            leg = below & side_mask
            ky = J[k]["K"][1]
            pieces["s" + k] = leg & (yy >= ky)
            th = leg & (yy < ky)
            # joint caps: copies (not cut out) so a rotated thigh / shin never leaves a gap at hip / knee
            pieces["s" + k + "_cap"] = _disc(alpha.shape, J[k]["K"], self.r_leg) & alpha & (yy < ky)
            pieces["t" + k] = th
            pieces["t" + k + "_cap"] = _disc(alpha.shape, J[k]["P"], (yc - J[k]["P"][1]) + self.r_leg) & alpha & ~below & hull
        legs_all = below
        arm_used = np.zeros_like(alpha)
        for k in ("n", "f"):
            # outside the body hull the sleeve can be wider than the capsule: take a wider band there
            up = (_capsule(alpha.shape, J[k]["S"], J[k]["E"], ru) | (_capsule(alpha.shape, J[k]["S"], J[k]["E"], 1.7 * ru) & ~hull)) & alpha & ~legs_all
            fo = (_capsule(alpha.shape, J[k]["E"], J[k]["T"], rf) | (_capsule(alpha.shape, J[k]["E"], J[k]["T"], 1.7 * rf) & ~hull)) & alpha & ~legs_all
            up &= ~fo
            # keep the shoulder itself on the torso: only pixels below the armpit-ish line move
            up &= ~(_disc(alpha.shape, J[k]["S"], 0.55 * ru) & hull)
            pieces["u" + k] = up & ~arm_used
            arm_used |= up
            pieces["f" + k] = fo & ~arm_used
            arm_used |= fo
            pieces["u" + k + "_cap"] = _disc(alpha.shape, J[k]["S"], 0.75 * ru) & alpha & ~legs_all
            pieces["f" + k + "_cap"] = _disc(alpha.shape, J[k]["E"], 0.8 * rf) & alpha & ~legs_all
        # hidden hand (in a pocket / behind the body): when that arm moves, the forearm is cut at the wrist
        # and a MIRRORED COPY of the person's other (visible) hand is attached as the fist.  The pocket area
        # is filled like any other uncovered body area.  Flagged in the build notes.
        self.fist = {}
        if colour_ref is not None and colour_ref.size == cut.size:
            Ac = np.zeros_like(A); Ac[padt:padt + h0, pad:pad + w0] = np.asarray(colour_ref.convert("RGBA"))
            A3 = Ac[..., :3].astype(int)
        else:
            A3 = A[..., :3].astype(int)
        skin = (A3[..., 0] > 70) & (A3[..., 0] > A3[..., 1] + 10) & (A3[..., 0] > A3[..., 2] + 8) & alpha
        hand_px = {}
        for k in ("n", "f"):
            c = J[k]["W"]; hc = ((J[k]["W"][0] + J[k]["T"][0]) / 2, (J[k]["W"][1] + J[k]["T"][1]) / 2)
            hand_px[k] = int((_disc(alpha.shape, hc, 0.3 * sw) & skin).sum())
        vis = max(hand_px, key=hand_px.get); hid = "n" if vis == "f" else "f"
        self.hand_visible, self.hand_hidden = vis, hid
        if hand_px[hid] < 0.6 * hand_px[vis]:     # hidden hand: build the fist from the visible one
            E_, W_, T_ = J[hid]["E"], J[hid]["W"], J[hid]["T"]
            d = np.array(_sub(T_, E_), float); d /= max(1e-6, np.hypot(*d))
            proj = (xx - E_[0]) * d[0] + (yy - E_[1]) * d[1]
            wproj = (W_[0] - E_[0]) * d[0] + (W_[1] - E_[1]) * d[1]
            fo_full = pieces["f" + hid]
            blue = (A3[..., 2] > A3[..., 1] + 12) & (A3[..., 2] > A3[..., 0] + 35)
            pieces["f" + hid + "_full"] = fo_full.copy()
            pieces["f" + hid] = fo_full & (proj <= wproj - 0.03 * sw) & ~blue & ~skin
            hc = ((J[vis]["W"][0] + J[vis]["T"][0]) / 2, (J[vis]["W"][1] + J[vis]["T"][1]) / 2)
            vh = _disc(alpha.shape, hc, 0.34 * sw) & skin & pieces["f" + vis]
            vh = ndi.binary_closing(vh, iterations=2) & alpha
            Lh = np.zeros_like(A); Lh[vh] = A[vh]
            Wv = J[vis]["W"]
            theta = _dir(E_, W_) - (-_dir(J[vis]["E"], Wv))
            Mm = np.array([[-1, 0, 2 * Wv[0]], [0, 1, 0], [0, 0, 1]], float)
            Mf = _tr(W_[0] - Wv[0], W_[1] - Wv[1]) @ _rot(theta, Wv) @ Mm
            img = Image.fromarray(Lh, "RGBA").transform((W, H), Image.AFFINE, tuple(np.linalg.inv(Mf)[:2].ravel()),
                                                         resample=Image.BICUBIC)
            self.fist[hid] = img
        torso = alpha & ~legs_all & ~arm_used
        known = torso & ~hull | (torso & hull)
        todo = arm_used & hull
        self.torso_rgba = _fill_from_nearest(A, todo, torso & ~todo)
        self.torso_mask = torso | todo
        self.pieces = pieces
        self.rest = {
            "un": _dir(J["n"]["S"], J["n"]["E"]), "fn": _dir(J["n"]["E"], J["n"]["T"]),
            "uf": _dir(J["f"]["S"], J["f"]["E"]), "ff": _dir(J["f"]["E"], J["f"]["T"]),
            "tn": _dir(J["n"]["P"], J["n"]["K"]), "sn": _dir(J["n"]["K"], J["n"]["A"]),
            "tf": _dir(J["f"]["P"], J["f"]["K"]), "sf": _dir(J["f"]["K"], J["f"]["A"]),
        }
        self.shape = alpha.shape
        self._layers = {}
        self._bbox = {}

    def layer(self, name):
        if name not in self._layers:
            if name.endswith("_fist"):
                self._layers[name] = self.fist[name[1]]
                return self._layers[name]
            if name == "torso":
                L = np.zeros_like(self.A); L[self.torso_mask] = self.torso_rgba[self.torso_mask]
            else:
                L = np.zeros_like(self.A); m = self.pieces[name]; L[m] = self.A[m]
            self._layers[name] = Image.fromarray(L, "RGBA")
        return self._layers[name]

    def debug_image(self):
        """rig.png: which pixels belong to which piece + joints"""
        cols = {"torso": (90, 90, 90), "un": (230, 60, 60), "fn": (250, 160, 40), "uf": (60, 90, 230), "ff": (60, 200, 230),
                "tn": (60, 200, 60), "sn": (170, 230, 60), "tf": (160, 60, 200), "sf": (230, 120, 220)}
        base = np.asarray(self.layer("torso")).copy()
        out = np.zeros_like(base)
        out[..., 3] = 0
        alpha = self.A[..., 3] > 0
        img = self.A.copy().astype(np.float32)
        for k, c in cols.items():
            m = self.torso_mask if k == "torso" else self.pieces[k]
            img[m, :3] = img[m, :3] * 0.45 + np.array(c) * 0.55
        im = Image.fromarray(img.clip(0, 255).astype(np.uint8), "RGBA")
        d = ImageDraw.Draw(im)
        for k in ("n", "f"):
            j = self.J[k]
            for a_, b_ in (("S", "E"), ("E", "T"), ("P", "K"), ("K", "A")):
                d.line([j[a_], j[b_]], fill=(255, 255, 255, 255), width=4)
            for p in j.values():
                d.ellipse((p[0] - 7, p[1] - 7, p[0] + 7, p[1] + 7), outline=(255, 255, 0, 255), width=3)
        d.line([(0, self.crotch), (im.width, self.crotch)], fill=(255, 0, 0, 255), width=2)
        bb = im.getchannel("A").getbbox()
        return im.crop(bb)

    # ------------------------------------------------------------------ pose -> image
    def render(self, pose):
        """pose: dict with segment directions (SEGS, absolute, deg from 'down'; missing = rest),
        lean (deg, + = top towards the opponent), lift (fraction of stand height, + = up, after grounding),
        sx / sy body squash, dx (fraction), effects: glow=(r,g,b) on hands 'glow_hands'='n'|'f'|'nf',
        orb=(r,g,b) + orb_hand, tint=(r,g,b,k)."""
        J, rest = self.J, self.rest
        pelvis = ((J["n"]["P"][0] + J["f"]["P"][0]) / 2, (J["n"]["P"][1] + J["f"]["P"][1]) / 2)
        M0 = _rot(-pose.get("lean", 0.0), pelvis) @ _scale(pose.get("sx", 1.0), pose.get("sy", 1.0), pelvis)
        def chain(k, a, b, ja, jb, jc):
            d1 = pose.get(a, rest[a]) - rest[a]
            d2 = (pose[b] - rest[b]) if b in pose else d1          # 2nd segment follows unless posed
            R1 = _rot(d1, J[k][ja])
            j2 = _ap(R1, J[k][jb])                                   # moved elbow / knee (before lean)
            M1 = M0 @ R1
            M2 = M0 @ _tr(j2[0] - J[k][jb][0], j2[1] - J[k][jb][1]) @ _rot(d2, J[k][jb])
            return M1, M2, _ap(M2, J[k][jc])
        H, W = self.shape
        canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        mats = {}
        for k in ("f", "n"):                       # legs first (behind the body)
            Mt, Ms, foot = chain(k, "t" + k, "s" + k, "P", "K", "A")
            mats["t" + k], mats["s" + k] = Mt, Ms
        for k in ("f", "n"):
            for nm in ("s" + k, "s" + k + "_cap", "t" + k + "_cap", "t" + k):
                M = mats[nm[:2]]
                self._warp(nm, M, canvas)
        self._warp("torso", M0, canvas)
        hands = {}
        order = pose.get("arm_order", ("f", "n"))
        for k in order:
            Mu, Mf, tip = chain(k, "u" + k, "f" + k, "S", "E", "T")
            seq = [("u" + k + "_cap", Mu), ("u" + k, Mu), ("f" + k + "_cap", Mf)]
            if k in self.fist:
                moved = max(abs(pose.get("u" + k, rest["u" + k]) - rest["u" + k]), abs(pose.get("f" + k, rest["f" + k]) - rest["f" + k]))
                seq += [("f" + k + "_full", Mf)] if moved < 12 else [("f" + k, Mf), ("f" + k + "_fist", Mf)]
            else:
                seq += [("f" + k, Mf)]
            for nm, M in seq:
                self._warp(nm, M, canvas)
            hands[k] = _ap(Mf, J[k]["W"]), tip
        a = np.asarray(canvas)
        rows = np.nonzero((a[..., 3] > 40).any(1))[0]
        low = int(rows.max()) if len(rows) else self.ground
        dy = self.ground - low - pose.get("lift", 0.0) * self.stand_h
        dx = pose.get("dx", 0.0) * self.stand_h
        out = canvas.transform(canvas.size, Image.AFFINE, (1, 0, -dx, 0, 1, -dy), resample=Image.BICUBIC)
        if pose.get("tint"):
            r, g, b, k = pose["tint"]
            arr = np.asarray(out).astype(np.float32)
            m = arr[..., 3] > 0
            arr[m, :3] = arr[m, :3] * (1 - k) + np.array([r, g, b]) * k
            out = Image.fromarray(arr.clip(0, 255).astype(np.uint8), "RGBA")
        fx = []
        for k in pose.get("glow_hands", ""):
            w_, t_ = hands[k]
            c = ((w_[0] + t_[0]) / 2 + dx, (w_[1] + t_[1]) / 2 + dy)
            fx.append(("glow", c, pose.get("glow", (120, 200, 255)), 0.07 * self.stand_h))
        if pose.get("orb"):
            ks = pose.get("orb_hand", "n")
            pts = [hands[k][1] for k in ks]
            c = (sum(p[0] for p in pts) / len(pts) + dx + pose.get("orb_ahead", 0.03) * self.stand_h,
                 sum(p[1] for p in pts) / len(pts) + dy)
            fx.append(("orb", c, pose["orb"], pose.get("orb_r", 0.05) * self.stand_h))
        for kind, c, col, r in fx:
            out = _effect(out, kind, c, col, r)
        return out

    def _warp(self, name, M, canvas):
        """transform one piece (only its bounding box) and composite it onto canvas"""
        L = self.layer(name)
        if name not in self._bbox:
            self._bbox[name] = L.getchannel("A").getbbox()
        bb = self._bbox[name]
        if not bb:
            return
        x0, y0, x1, y1 = bb
        pts = [_ap(M, (x, y)) for x in (x0, x1) for y in (y0, y1)]
        ox, oy = int(math.floor(min(p[0] for p in pts))) - 2, int(math.floor(min(p[1] for p in pts))) - 2
        ex, ey = int(math.ceil(max(p[0] for p in pts))) + 2, int(math.ceil(max(p[1] for p in pts))) + 2
        ox, oy = max(0, ox), max(0, oy)
        ex, ey = min(canvas.width, ex), min(canvas.height, ey)
        if ex <= ox or ey <= oy:
            return
        Mi = np.linalg.inv(M) @ _tr(ox, oy)
        Mi = _tr(-x0, -y0) @ Mi
        src = L.crop(bb)
        piece = src.transform((ex - ox, ey - oy), Image.AFFINE, tuple(Mi[:2].ravel()), resample=Image.BICUBIC)
        canvas.alpha_composite(piece, (ox, oy))


def _sub(p, q):
    return (p[0] - q[0], p[1] - q[1])


def _effect(im, kind, c, col, r):
    """procedural light effect (not part of the person): soft glow, or an energy orb with a hot core"""
    W, H = im.size
    x0, y0 = int(max(0, c[0] - 3 * r)), int(max(0, c[1] - 3 * r))
    x1, y1 = int(min(W, c[0] + 3 * r)), int(min(H, c[1] + 3 * r))
    if x1 <= x0 or y1 <= y0:
        return im
    yy, xx = np.mgrid[y0:y1, x0:x1]
    d = np.sqrt((xx - c[0]) ** 2 + (yy - c[1]) ** 2) / r
    fx = np.zeros((y1 - y0, x1 - x0, 4), np.float32)
    if kind == "glow":
        al = np.exp(-d * d * 1.3) * 0.75
        fx[..., :3] = col
    else:
        al = np.clip(np.exp(-(np.maximum(d - 0.6, 0)) ** 2 * 3.0), 0, 1)
        core = np.clip(1.2 - d, 0, 1)
        fx[..., :3] = np.array(col) * (1 - core[..., None]) + np.array([255, 255, 250]) * core[..., None]
    fx[..., 3] = al * 255
    layer = Image.new("RGBA", im.size, (0, 0, 0, 0))
    layer.paste(Image.fromarray(fx.clip(0, 255).astype(np.uint8), "RGBA"), (x0, y0))
    if kind == "glow":
        out = Image.alpha_composite(layer, im)       # glow behind the hand
        out = Image.alpha_composite(out, _fade(layer, 0.35))
        return out
    return Image.alpha_composite(im, layer)


def _fade(layer, k):
    a = np.asarray(layer).copy()
    a[..., 3] = (a[..., 3] * k).astype(np.uint8)
    return Image.fromarray(a, "RGBA")


