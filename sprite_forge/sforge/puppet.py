def _lerp(a, b, t):
    out = {}
    for k in set(a) | set(b):
        va, vb = a.get(k), b.get(k)
        if isinstance(va, (int, float)) and isinstance(vb, (int, float)):
            out[k] = va + (vb - va) * t
        elif va is None and isinstance(vb, (int, float)) and k in ("lean", "lift", "dx"):
            out[k] = vb * t
        elif vb is None and isinstance(va, (int, float)) and k in ("lean", "lift", "dx"):
            out[k] = va * (1 - t)
        else:
            out[k] = vb if (t >= 0.5 and vb is not None) or va is None else va
    return out


def _sample(keys, n):
    """n poses from key poses spread evenly over the move"""
    if n <= len(keys):
        idx = np.linspace(0, len(keys) - 1, n)
    else:
        idx = np.linspace(0, len(keys) - 1, n)
    out = []
    for f in idx:
        i = int(math.floor(f)); t = f - i
        if i >= len(keys) - 1:
            out.append(dict(keys[-1]))
        else:
            out.append(_lerp(keys[i], keys[i + 1], t))
    return out


