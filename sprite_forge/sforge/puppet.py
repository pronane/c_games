def render_moves(cut, landmarks, moves, log=print):
    """moves: list of (name, n_frames) -> {name: [RGBA canvas, ...]}, rig"""
    rig = Rig(cut, landmarks)
    out = {}
    for name, n in moves:
        keys, cyclic = move_keys(name, rig.rest, n)
        poses = keys if len(keys) == n else _sample(keys, n)
        out[name] = [rig.render(p) for p in poses]
    return out, rig
