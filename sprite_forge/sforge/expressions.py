def head_box(im, frac=0.30):
    """square around the head of a sprite frame (top of the figure); returns crop box or None"""
    a = np.asarray(im.getchannel("A")) > 60
    rows = np.nonzero(a.any(1))[0]
    if not len(rows):
        return None
    top, bot = int(rows[0]), int(rows[-1])
    h = bot - top + 1
    side = max(8, int(h * frac))
    band = a[top:top + max(2, side // 2)]
    xs = np.nonzero(band.any(0))[0]
    cx = int((xs.min() + xs.max()) / 2) if len(xs) else im.width // 2
    y0 = max(0, top - side // 10)
    return (cx - side // 2, y0, cx - side // 2 + side, y0 + side)


def faces_sheet(images, labels, title="", thumb=128, cols=0):
    """labelled grid of head close-ups (HUD portraits / expression check); cols=0 -> one row up to 8 wide"""
    from .build import checker, _font
    n = len(images)
    cols = cols or min(n, 8)
    rows = (n + cols - 1) // cols
    cw, ch = thumb + 8, thumb + 24
    oy = 24 if title else 6
    sheet = Image.new("RGB", (max(cols * cw + 8, 8 + 7 * len(title)), oy + rows * ch + 4), (32, 36, 44))
    d = ImageDraw.Draw(sheet)
    if title:
        d.text((8, 4), title, fill=(230, 230, 230), font=_font(13))
    for i, (im, lb) in enumerate(zip(images, labels)):
        x, y = 8 + (i % cols) * cw, oy + (i // cols) * ch
        bg = checker(thumb, thumb, 8)
        if im is not None:
            t = im.copy(); t.thumbnail((thumb, thumb), Image.LANCZOS)
            if t.mode != "RGBA":
                t = t.convert("RGBA")
            bg.paste(t, ((thumb - t.width) // 2, (thumb - t.height) // 2), t)
        sheet.paste(bg, (x, y))
        d.text((x + 2, y + thumb + 4), lb, fill=(235, 235, 235), font=_font(12))
    return sheet
