"""v9 FACES: dynamic facial expressions + mouth shapes (visemes) for talking.

Expressions: neutral happy angry hurt shout taunt blink.  Mouth shapes: rest mbp ai e o u fv l.

* Mannequin / SPEC characters: the 3D face (brows, eyelids, three-piece mouth, teeth) is rebuilt per expression with
  the SAME triangles in different places, so the GLB also gets one morph target (blend shape) per expression /
  mouth shape and every clip a 'weights' track (sforge/gltf.py).
* Photo characters: PROCEDURAL WARPS of the user's own photo pixels (mouth corners, jaw, brows, lower lids) plus
  small drawn overlays (closed eyelids from the person's own skin colour, the dark inside of an open mouth, teeth).
  Nothing is generated by AI and no new picture of the person is invented; every result is labelled ESTIMATED.
* Per-move mapping: punch -> angry, hit -> hurt, victory -> happy ... (DEFAULT_MAP + keyword rules), changed with
  --expr-map "hit=hurt,taunt=happy"; looping neutral moves blink once per loop (--blink off to stop).
"""
from __future__ import annotations
import math
import re
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

EXPRESSIONS = ["neutral", "happy", "angry", "hurt", "shout", "taunt", "blink"]
VISEMES = ["rest", "mbp", "ai", "e", "o", "u", "fv", "l"]
VISEME_HELP = {"rest": "closed, relaxed", "mbp": "M B P (lips pressed)", "ai": "A I (wide open)", "e": "E (wide, a little open)",
               "o": "O (round)", "u": "U W Q (small round)", "fv": "F V (teeth on lip)", "l": "L TH D (open, tongue)"}

# face parameters (all optional, 0 = neutral):
#   brow_in  +1 inner ends down (angry) / -1 inner ends up (worried)   brow_up  both brows up   brow_one  one brow up
#   lid      0 open .. 1 closed        squint  lower+upper lid tighten
#   mouth_open 0..1   mouth_w  width x   corner  +1 corners up (smile) / -1 down   smirk  one corner up
#   teeth 0/1   press 0/1 (lips pressed)   tongue 0/1
PARAMS = {
    "neutral": {},
    "happy": dict(corner=1.0, mouth_w=1.15, mouth_open=0.18, teeth=1, squint=0.3, brow_up=0.25),
    "angry": dict(brow_in=1.0, corner=-0.5, mouth_w=0.95, squint=0.35, mouth_open=0.12, teeth=1),
    "hurt": dict(brow_in=-1.0, squint=0.75, corner=-0.7, mouth_open=0.35, mouth_w=1.08, teeth=1),
    "shout": dict(brow_in=0.7, brow_up=0.2, mouth_open=1.0, mouth_w=1.0, corner=-0.15, teeth=1),
    "taunt": dict(smirk=1.0, brow_one=1.0, squint=0.2, mouth_w=1.05),
    "blink": dict(lid=1.0),
}
VISEME_PARAMS = {
    "rest": {}, "mbp": dict(press=1.0, mouth_w=0.95),
    "ai": dict(mouth_open=0.75, mouth_w=1.08, teeth=1), "e": dict(mouth_open=0.28, mouth_w=1.28, teeth=1),
    "o": dict(mouth_open=0.6, mouth_w=0.72), "u": dict(mouth_open=0.22, mouth_w=0.55),
    "fv": dict(mouth_open=0.14, teeth=1, press=0.5), "l": dict(mouth_open=0.45, tongue=1, teeth=1),
}

DEFAULT_MAP = {"idle": "neutral", "fight_idle": "neutral", "walk": "neutral", "run": "neutral", "crouch": "neutral",
               "jump": "neutral", "punch": "angry", "kick": "angry", "block": "angry", "guard": "angry", "throw": "angry",
               "hit": "hurt", "taunt": "taunt", "victory": "happy", "jump_attack": "shout", "jumpattack": "shout",
               "pyramid_blast": "shout", "bum_fireball": "shout", "special1": "shout", "special2": "shout",
               "special_1": "shout", "special_2": "shout", "talk": "neutral", "wave": "happy"}
_RULES = [(r"hit|hurt|fall|ko|knock|injur|defeat|death|die|spin_out|stun", "hurt"),
          (r"victory|celebr|cheer|win|wave|dance", "happy"),
          (r"special|blast|fireball|boost|shout|cast|roar|super", "shout"),
          (r"taunt|tease", "taunt"),
          (r"punch|kick|tackle|throw|attack|block|guard|shoot|slash|strike|bite|claw|swing", "angry")]


def all_names():
    return EXPRESSIONS + ["mouth_" + v for v in VISEMES]


def params_for(name):
    """'angry' | 'mouth_ai' | 'angry+mouth_o' (an expression with a mouth shape on top) -> parameter dict"""
    p = {}
    for part in str(name or "neutral").split("+"):
        part = part.strip().lower()
        if part.startswith("mouth_"):
            v = VISEME_PARAMS.get(part[6:])
            if v is None:
                raise ValueError("unknown mouth shape '%s' (use %s)" % (part, ", ".join(VISEMES)))
            for k in ("mouth_open", "mouth_w", "corner", "smirk", "teeth", "press", "tongue"):
                p.pop(k, None)
            p.update(v)
        else:
            if part not in PARAMS:
                raise ValueError("unknown expression '%s' (use %s)" % (part, ", ".join(EXPRESSIONS)))
            p.update(PARAMS[part])
    return p


def parse_map(s):
    """'hit=hurt,victory=happy' -> dict ; 'off' / 'none' -> {'*': None}"""
    s = (s or "").strip()
    if not s:
        return {}
    if s.lower() in ("off", "none", "no"):
        return {"*": None}
    out = {}
    for part in s.split(","):
        if "=" not in part:
            raise ValueError("--expr-map wants move=expression pairs, e.g. hit=hurt,victory=happy (got '%s')" % part)
        k, v = [x.strip().lower() for x in part.split("=", 1)]
        params_for(v)
        out[k] = v
    return out


def expression_for(move, user_map=None):
    um = user_map or {}
    if um.get("*", "x") is None:
        return "neutral"
    m = move.lower()
    if m in um:
        return um[m]
    if m in DEFAULT_MAP:
        return DEFAULT_MAP[m]
    for rx, e in _RULES:
        if re.search(rx, m):
            return e
    return "neutral"


def schedule(move, n, loop, user_map=None, blink=True):
    """expression per frame of one move.  Attack 'shout' moves wind up angry and shout in the middle;
    looping neutral moves blink on one frame per loop."""
    e = expression_for(move, user_map)
    out = [e] * n
    if e == "shout" and n >= 4 and not (user_map or {}).get(move.lower()):
        for i in range(n):
            t = i / max(1, n - 1)
            if t < 0.25:
                out[i] = "angry"
    if blink and e == "neutral" and loop and n >= 4:
        out[n // 2] = "blink"
    return out


# ------------------------------------------------------------------ text -> mouth shapes (for talk strips)
_VIS_RULES = [("th", "l"), ("ch", "e"), ("sh", "e"), ("oo", "u"), ("ee", "e"), ("ou", "o"), ("ow", "o")]
_VIS_CH = {"a": "ai", "i": "ai", "e": "e", "o": "o", "u": "u", "w": "u", "q": "u", "m": "mbp", "b": "mbp", "p": "mbp",
           "f": "fv", "v": "fv", "l": "l", "d": "l", "t": "l", "n": "l", "y": "e", "c": "e", "s": "e", "z": "e",
           "k": "e", "g": "e", "j": "e", "x": "e", "r": "o", "h": "ai"}


def text_to_visemes(text, fps=12):
    """rough letter-based mouth shapes for a line of dialogue (not speech recognition): list of (viseme, frames)"""
    t = text.lower()
    seq = []
    i = 0
    while i < len(t):
        two = t[i:i + 2]
        hit = next((v for k, v in _VIS_RULES if two == k), None)
        if hit:
            seq.append(hit); i += 2; continue
        ch = t[i]
        if ch.isalpha():
            seq.append(_VIS_CH.get(ch, "rest"))
        elif ch in " ,;:-":
            seq.append("rest")
        elif ch in ".!?":
            seq += ["rest", "rest"]
        i += 1
    out = []
    for v in seq:          # merge repeats; vowels 2 frames, consonants 1
        if out and out[-1][0] == v:
            continue
        out.append([v, 2 if v in ("ai", "e", "o", "u") else 1])
    if not out or out[-1][0] != "rest":
        out.append(["rest", 2])
    return [tuple(x) for x in out]


# ------------------------------------------------------------------ PHOTO faces (warps of the user's own pixels)
def face_from_landmarks(L):
    """MediaPipe pose ids: 0 nose, 2 / 5 eye centres, 9 / 10 mouth corners. Points in the image's coordinates."""
    P = lambda i: np.array(L[i][:2], float)
    eyes = sorted([P(2), P(5)], key=lambda p: p[0])
    mouth = sorted([P(9), P(10)], key=lambda p: p[0])
    Em, Cm = (eyes[0] + eyes[1]) / 2, (mouth[0] + mouth[1]) / 2
    s = float(np.hypot(*(Em - Cm)))
    if s < 2:
        raise ValueError("face landmarks too small / missing")
    u = (Em - Cm) / s
    r = np.array([-u[1], u[0]])
    if r[0] < 0:
        r = -r
    return dict(eyes=eyes, mouth=mouth, nose=P(0), Em=Em, Cm=Cm, s=s, u=u, r=r,
                mw=max(float(np.hypot(*(mouth[1] - mouth[0]))), 0.35 * s), ew=float(np.hypot(*(eyes[1] - eyes[0]))))


def _gauss(xx, yy, c, sig):
    return np.exp(-(((xx - c[0]) ** 2 + (yy - c[1]) ** 2) / (2.0 * sig * sig)))


def _smooth(t, a, b):
    x = np.clip((t - a) / max(1e-6, b - a), 0, 1)
    return x * x * (3 - 2 * x)


def warp_face(img, face, p, label=False):
    """procedural expression on a photo: displacement warp of the face pixels + small drawn overlays.
    img: RGBA (the torso/head layer or the whole cut-out).  Returns a new RGBA image."""
    from scipy import ndimage as ndi
    if not p:
        return img
    f = face
    s, u, r, Cm, Em = f["s"], f["u"], f["r"], f["Cm"], f["Em"]
    A = np.asarray(img.convert("RGBA")).astype(np.float32)
    H, W = A.shape[:2]
    R = 1.6 * s
    cx, cy = (Em + Cm) / 2
    x0, y0 = int(max(0, cx - R - 2)), int(max(0, cy - R - 2))
    x1, y1 = int(min(W, cx + R + 2)), int(min(H, cy + R * 1.2 + 2))
    if x1 - x0 < 4 or y1 - y0 < 4:
        return img
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    D = np.zeros(xx.shape + (2,), np.float32)
    def push(c, vec, sig):
        g = _gauss(xx, yy, c, sig)
        D[..., 0] += g * vec[0]; D[..., 1] += g * vec[1]
    mw = f["mw"]
    side_on = f["ew"] < 0.35 * s
    # mouth corners: up / down, width
    corner, smirk, mwid = p.get("corner", 0.0), p.get("smirk", 0.0), p.get("mouth_w", 1.0)
    for i, c in enumerate(f["mouth"]):
        out_dir = r * (1 if i == 1 else -1)
        lift = corner * 0.16 * s + (smirk * 0.18 * s if i == 1 else 0.0)
        vec = u * lift + out_dir * (mwid - 1.0) * 0.5 * mw
        if abs(lift) + abs(mwid - 1) > 1e-4:
            push(c, vec, 0.2 * s)
    # lips pressed (M B P): pull the lips together and thin them
    if p.get("press"):
        push(Cm + u * 0.08 * s, -u * 0.03 * s * p["press"], 0.12 * s)
        push(Cm - u * 0.08 * s, u * 0.03 * s * p["press"], 0.12 * s)
    # brows
    for i, e in enumerate(f["eyes"]):
        inner = r * (1 if i == 0 else -1)          # towards the other eye
        b = e + u * 0.30 * s
        if side_on:
            inner = r * 0.0
        bi, bo = b + inner * 0.12 * s, b - inner * 0.12 * s
        dy_in = -p.get("brow_in", 0.0) * 0.09 * s + p.get("brow_up", 0.0) * 0.08 * s
        dy_out = p.get("brow_up", 0.0) * 0.08 * s + p.get("brow_in", 0.0) * 0.02 * s
        if p.get("brow_one") and i == 0:
            dy_in += 0.10 * s * p["brow_one"]; dy_out += 0.12 * s * p["brow_one"]
        if dy_in:
            push(bi, u * dy_in, 0.11 * s)
        if dy_out:
            push(bo, u * dy_out, 0.11 * s)
        sq = p.get("squint", 0.0)
        if sq:
            push(e - u * 0.09 * s, u * 0.045 * s * sq, 0.07 * s)
            push(e + u * 0.07 * s, -u * 0.03 * s * sq, 0.07 * s)
    # jaw / lower lip down
    op = p.get("mouth_open", 0.0)
    gap = op * 0.30 * s
    if op > 0:
        rel = np.stack([xx - Cm[0], yy - Cm[1]], -1)
        t_down = (rel @ (-u)) / s
        t_side = (rel @ r) / (0.6 * mw * max(0.6, mwid) + 0.3 * s)
        w = _smooth(t_down, -0.02, 0.10) * (1 - _smooth(t_down, 0.55, 0.95)) * np.exp(-t_side ** 2)
        D[..., 0] += w * (-u[0]) * gap; D[..., 1] += w * (-u[1]) * gap
    out = A.copy()
    if np.abs(D).max() > 0.05:
        sx, sy = xx - D[..., 0], yy - D[..., 1]
        for ch in range(4):
            out[y0:y1, x0:x1, ch] = ndi.map_coordinates(A[..., ch], [sy, sx], order=1, mode="nearest")
    img2 = Image.fromarray(out.clip(0, 255).astype(np.uint8), "RGBA")
    # ---- overlays drawn at 4x then reduced (anti-aliased), only where the face has pixels
    ss = 4
    pw, ph = x1 - x0, y1 - y0
    ov = Image.new("RGBA", (pw * ss, ph * ss), (0, 0, 0, 0))
    dr = ImageDraw.Draw(ov)
    def P(q):
        return ((q[0] - x0) * ss, (q[1] - y0) * ss)
    def ell(c, a, b, fill):
        # ellipse with axes along r (a) and u (b): polygon
        pts = [P(c + r * a * math.cos(t) + u * b * math.sin(t)) for t in np.linspace(0, 2 * math.pi, 40)]
        dr.polygon(pts, fill=fill)
    def sample(c, rad):
        i0, j0 = int(max(0, c[1] - rad)), int(max(0, c[0] - rad))
        patch = A[i0:int(c[1] + rad) + 1, j0:int(c[0] + rad) + 1]
        m = patch[..., 3] > 200
        if not m.any():
            return np.array([150.0, 110, 90])
        return np.median(patch[m][:, :3], axis=0)
    drawn = False
    def cheek_skin(e):
        cands = [sample(e + u * 0.18 * s, 0.05 * s), sample(e - u * 0.28 * s, 0.05 * s)]
        return 0.5 * (cands[0] + cands[1]) * 0.94
    # mouth corners where the warp moved them
    Cw = []
    for i, c in enumerate(f["mouth"]):
        out_dir = r * (1 if i == 1 else -1)
        lift = corner * 0.16 * s + (smirk * 0.18 * s if i == 1 else 0.0)
        Cw.append(c + u * lift + out_dir * (mwid - 1.0) * 0.5 * mw)
    if side_on:
        mid = (Cw[0] + Cw[1]) / 2
        Cw = [mid + (q - mid) * 0.6 for q in Cw]
    def lip_curve(t, k):
        return Cw[0] + (Cw[1] - Cw[0]) * t + k
    if gap >= 0.06 * s:
        lip = sample(Cm, 0.06 * s)
        dark = tuple(int(v) for v in np.clip(lip * np.array([0.30, 0.16, 0.16]) + np.array([16, 3, 3]), 0, 255))
        ts = np.linspace(0.07, 0.93, 24)
        up_b = 0.02 * s + gap * 0.12
        upper = [lip_curve(t, u * up_b * math.sin(math.pi * t)) for t in ts]
        lower = [lip_curve(t, -u * gap * math.sin(math.pi * t) ** 0.8) for t in ts[::-1]]
        dr.polygon([P(q) for q in upper + lower], fill=dark + (255,))
        if p.get("teeth"):
            skin = cheek_skin(f["eyes"][0])
            br = float(np.clip(skin.mean() / 160.0, 0.7, 1.05))
            tooth = tuple(int(min(255, v * br)) for v in (214, 204, 188))
            tb = min(0.30 * gap, 0.05 * s)
            band = upper + [lip_curve(t, u * up_b * math.sin(math.pi * t) - u * tb * math.sin(math.pi * t) ** 0.4) for t in ts[::-1]]
            dr.polygon([P(q) for q in band], fill=tooth + (255,))
        if p.get("tongue"):
            ts2 = np.linspace(0.25, 0.75, 12)
            tg = [lip_curve(t, -u * gap * 0.55 * math.sin(math.pi * t)) for t in ts2]
            tg += [lip_curve(t, -u * gap * 0.95 * math.sin(math.pi * t) ** 0.8) for t in ts2[::-1]]
            dr.polygon([P(q) for q in tg], fill=(178, 72, 82, 255))
        drawn = True
    elif gap > 0 or p.get("press"):
        # barely open / pressed: only a soft darker lip line (no drawn interior)
        k = 0.55 if p.get("press") else 0.7
        dr.line([P(lip_curve(t, -u * gap * 0.5 * math.sin(math.pi * t))) for t in np.linspace(0.1, 0.9, 16)],
                fill=(30, 10, 10, int(255 * (1 - k))), width=max(1, int(0.03 * s * ss)))
        drawn = True
    lid = p.get("lid", 0.0)
    if lid > 0.05:
        for e in f["eyes"]:
            skin = cheek_skin(e)
            ea = (0.15 * s if not side_on else 0.10 * s)
            if not side_on:
                ea = min(ea, 0.40 * f["ew"])
            eb = 0.08 * s
            col = tuple(int(v) for v in skin) + (255,)
            shade = tuple(int(v * 0.86) for v in skin) + (255,)
            lo = 1.0 - 1.75 * lid            # lid edge position (1 = top of the eye, -0.75 = closed)
            sag = 0.25 * eb * lid            # a closed lid curves down a little
            top = [e + r * ea * 1.12 * math.cos(t) + u * eb * 1.2 * math.sin(t) for t in np.linspace(0, math.pi, 20)]
            edge = [e + r * ea * 1.12 * math.cos(t) + u * (eb * lo - sag * math.sin(t)) for t in np.linspace(math.pi, 0, 14)]
            dr.polygon([P(q) for q in top + edge], fill=col)
            dr.line([P(q) for q in edge], fill=shade, width=max(1, int(0.05 * s * ss)))
            lash = tuple(int(v * 0.32) for v in skin) + (230,)
            dr.line([P(q) for q in edge[2:-2]], fill=lash, width=max(1, int(0.014 * s * ss)))
        drawn = True
    if drawn:
        ov = ov.filter(ImageFilter.GaussianBlur(max(0.5, 0.35 * ss))).resize((pw, ph), Image.LANCZOS)
        oa = np.asarray(ov).astype(np.float32)
        base = np.asarray(img2).astype(np.float32)
        reg = base[y0:y1, x0:x1]
        al = oa[..., 3:4] / 255.0 * (reg[..., 3:4] > 100)
        reg[..., :3] = reg[..., :3] * (1 - al) + oa[..., :3] * al
        base[y0:y1, x0:x1] = reg
        img2 = Image.fromarray(base.clip(0, 255).astype(np.uint8), "RGBA")
    return img2


class PhotoFaces:
    """expressions for a photo puppet rig (sforge.puppet.Rig or sforge.turn.SideRig): the head is in the rig's
    'torso' layer; each expression is a warped copy of that layer."""

    def __init__(self, rig, face_pts):
        self.rig = rig
        self.face = face_from_landmarks(face_pts)
        self.base = rig.layer("torso").copy()
        self._cache = {}

    def layer(self, name):
        if name not in self._cache:
            p = params_for(name)
            self._cache[name] = self.base if not p else warp_face(self.base, self.face, p)
        return self._cache[name]

    def use(self, name):
        self.rig._layers["torso"] = self.layer(name)
        self.rig._bbox.pop("torso", None)


def rig_face_points(rig, landmarks, turned_res=None):
    """face landmarks (0..10) in the rig's padded canvas coordinates"""
    if turned_res is not None and math.cos(math.radians(getattr(turned_res, "yaw", 0.0))) < -0.2:
        raise ValueError("the face is not visible from behind (turn %g)" % turned_res.yaw)
    if getattr(rig, "side", False) and turned_res is not None:
        from .turn import project_landmarks
        pl = project_landmarks(turned_res, landmarks)
        return [(x + rig.pad, y + rig.padt) for x, y, _ in pl[:11]]
    return [tuple(p) for p in rig.L[:11]]


