"""v8 TURN: show a front-photo cut-out from another angle (--turn 0|90|180|270, or any --turn-yaw).

ONE front photo has no pixels of the person's side or back, so the side view is an ESTIMATE built from the
person's own pixels:

  1. the cut-out is split into body parts (head+torso, upper/fore arms, thighs, shins+feet) with the pose
     landmarks of `forge.py cutout` (the same split as the photo puppet);
  2. every image row of every part becomes a horizontal cross-section: its WIDTH is measured in the photo,
     its DEPTH comes from one of three sources (--turn-depth):
       template  a CC0 MakeHuman body from the Sprite Forge library (forge.py human --setup): the template's
                 own cross-section at the same body height (chest, bottom, chin, nose, foot length ...),
                 scaled to the photo's width                                       (default when installed)
       relief    procedural: ellipses with typical depth/width ratios per body region   (always available)
       side      as template/relief, then every row's front/back extent is fitted to the silhouette of a
                 SIDE photo (or a frame of a side video) of the same person (--side-photo), whose pixels
                 also colour the side-facing surfaces
  3. the photo is projected onto the FRONT of that model; the BACK gets the colour of the part's own edge
     pixels (sides of the sweater, jeans, head ...) - logos / text / face are never copied to the back;
  4. the model is turned about the vertical axis and drawn again, one layer per body part, so the photo
     puppet can animate a real side-on fighter (near arm in front of the body, far arm behind it).

Nothing is generated by AI and no other person's pixels are used.  Hidden detail (the far side, the back, a
hand in a pocket) is estimated, and the README / build report says so.
yaw: degrees the person turns to HIS LEFT: 90 = faces image-right (shows his right side), 180 = back,
270 = faces image-left (shows his left side).
"""
from __future__ import annotations
import math, os
import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage as ndi

PART_NAMES = ("torso", "un", "fn", "uf", "ff", "tn", "sn", "tf", "sf")
SS_X = 2          # horizontal supersampling of the turned render
SS_SAMPLES = 3    # cross-section samples per source pixel


# ------------------------------------------------------------------ helpers
def _edge_fixed_rgb(a, inset=3):
    """colours of soft matte-edge pixels (and a thin inner ring, which carries background spill / rim light)
    replaced by the nearest interior pixel: a turned view shows the photo's edge columns stretched across the
    side of the body, so a light halo there would paint the whole side"""
    rgb = a[..., :3].copy()
    solid = a[..., 3] >= 230
    if inset > 0:
        core = ndi.binary_erosion(solid, iterations=inset)
        if core.sum() > 0.5 * solid.sum():
            solid = core
    if solid.any():
        _, (iy, ix) = ndi.distance_transform_edt(~solid, return_indices=True)
        soft = (a[..., 3] > 0) & ~solid
        rgb[soft] = a[iy[soft], ix[soft], :3]
    return rgb


def _runs(row):
    """[x0, x1] runs of True in a 1-D bool array"""
    if not row.any():
        return []
    d = np.diff(np.concatenate([[0], row.astype(np.int8), [0]]))
    s = np.nonzero(d == 1)[0]; e = np.nonzero(d == -1)[0] - 1
    return list(zip(s, e))


def _interp_keys(y, ys, vs):
    return float(np.interp(y, ys, vs))


# ------------------------------------------------------------------ depth sources
class Relief:
    """procedural depth: ellipse cross-sections, depth = k * width, typical ratios per body region"""
    name = "relief"

    def __init__(self, geo):
        self.g = geo

    def section(self, part, y, x0, x1, u):
        g = self.g
        w = float(x1 - x0 + 1)
        H = g["stand_h"]
        zc = 0.0
        if part == "torso":
            ys = [g["top"], g["chin"], g["neck"], g["shoulder"], g["chest"], g["waist"], g["hip"], g["crotch"]]
            ks = [1.15, 1.25, 1.0, 0.55, 0.62, 0.66, 0.72, 0.80]
            zs = [0.012, 0.022, 0.0, 0.0, 0.010, 0.004, -0.010, -0.006]
            k = _interp_keys(y, ys, ks); zc = _interp_keys(y, ys, zs) * H
            d = k * w
        elif part[0] in "uf":
            d = min(w, 1.15 * g.get("arm_w_" + part, 1e9))
            zc = self.g["arm_z"]
        else:
            d = (1.05 if part[0] == "t" else 0.95) * w
            # feet: long (forwards) instead of round
            ank, gr = g["ankle"][part[1]], g["ground"]
            if y > ank - 0.012 * H:
                t = min(1.0, (y - (ank - 0.012 * H)) / max(1.0, gr - ank + 0.012 * H))
                t = math.sqrt(max(0.0, t))
                d = d + t * (0.150 * H - d)
                zc = t * 0.040 * H
        e = np.sqrt(np.clip(1 - u * u, 0, 1))
        return zc + 0.5 * d * e, zc - 0.5 * d * e


class Template:
    """CC0 MakeHuman body from the Sprite Forge library: real cross-sections at the same body height"""
    name = "template"

    def __init__(self, geo, params=None, assets=None, log=print):
        from . import human
        self.g = geo
        p = {"gender": 1.0, "age": 0.55, "muscle": 0.5, "weight": 0.55}
        p.update(params or {})
        r = human.build(p, assets=assets, log=lambda *a: None)
        V = np.asarray(r.V, float)
        dom = np.asarray(r.J)[np.arange(len(V)), np.argmax(np.asarray(r.W), 1)]
        names = [r.bones[i] for i in dom]
        arm = np.array([any(n.startswith(s) for s in ("clavicle", "shoulder", "upperarm", "lowerarm", "wrist", "finger"))
                        for n in names])
        leg = np.array([any(n.startswith(s) for s in ("upperleg", "lowerleg", "foot", "toe")) for n in names])
        left = V[:, 0] > 0
        bp = {b: r.bind[i][:3, 3] for i, b in enumerate(r.bones)}
        self.Ht = float(V[:, 1].max())
        # crotch height of the template: lowest non-leg vertex near the middle
        mid = (~arm) & (~leg) & (np.abs(V[:, 0]) < 0.05)
        self.crotch_t = float(V[mid, 1].min()) if mid.any() else float(bp["upperleg01.L"][1] - 0.08)
        self.keys_t = dict(ground=0.0, ankle=float(bp["foot.L"][1]), knee=float(bp["lowerleg01.L"][1]),
                           hip=float(bp["upperleg01.L"][1]), shoulder=float(bp["upperarm01.L"][1]), top=self.Ht)
        F = np.asarray(r.F, int)
        def tris(vm):                # triangles whose 3 vertices are all in the group
            ok = vm[F].all(1)
            return V[F[ok]]          # (n, 3, 3)
        self.groups = {"torso": tris(~arm), "n": tris(leg & left), "f": tris(leg & ~left)}
        self.groups_upper = tris((~arm) & (~leg))
        self.zc_shoulder = None
        self.params = p
        self._cache = {}
        g = geo
        # photo row -> template height, piecewise linear through matching body landmarks
        py = [g["ground"], g["ankle_m"], g["knee_m"], g["hip_m"], g["shoulder"], g["top"]]
        ty = [0.0, self.keys_t["ankle"], self.keys_t["knee"], self.keys_t["hip"], self.keys_t["shoulder"], self.Ht]
        order = np.argsort(py)
        self.py = np.array(py)[order]; self.ty = np.array(ty)[order]
        self.S = g["stand_h"] / self.Ht            # photo px per template metre
        log("turn: template = MakeHuman CC0 body (%s), %.2f m, %d verts" % (
            ", ".join("%s=%.2f" % kv for kv in p.items()), self.Ht, len(V)))

    def Yt(self, y):
        return float(np.interp(y, self.py, self.ty))

    def _slice(self, key, Yt, nb=24):
        """exact cross-section of the template mesh at height Yt (triangle / plane intersection)"""
        k = (key, int(round(Yt / 0.003)))
        if k in self._cache:
            return self._cache[k]
        T = self.groups[key]        # torso = every non-arm triangle (hips / tops of the thighs included)
        pts = self._cut(T, Yt)
        dy = 0.003
        while len(pts) < 6 and dy < 0.05:          # above the head top / below the soles: nearest slice
            pts = self._cut(T, Yt - dy) if Yt > 0.5 else self._cut(T, Yt + dy)
            dy *= 2
        if len(pts) < 2:
            pts = np.array([[-0.05, 0.0], [0.05, 0.0]])
        x0, x1 = pts[:, 0].min(), pts[:, 0].max()
        xc, hw = 0.5 * (x0 + x1), max(1e-3, 0.5 * (x1 - x0))
        u = (pts[:, 0] - xc) / hw
        b = np.clip(((u + 1) / 2 * nb).astype(int), 0, nb - 1)
        zf = np.full(nb, -np.inf); zb = np.full(nb, np.inf)
        np.maximum.at(zf, b, pts[:, 1]); np.minimum.at(zb, b, pts[:, 1])
        ok = np.isfinite(zf)
        c = (np.arange(nb) + 0.5) / nb * 2 - 1
        zf = np.interp(c, c[ok], zf[ok]); zb = np.interp(c, c[ok], zb[ok])
        zm = 0.5 * (zf + zb)
        e = np.sqrt(np.clip(1 - c * c, 0, 1)) ** 0.35
        zf = zm + (zf - zm) * e; zb = zm + (zb - zm) * e
        out = (c, zf, zb, xc, hw)
        self._cache[k] = out
        return out

    @staticmethod
    def _cut(T, Yt, dens=12):
        """contour points of the mesh section at Yt: every crossed triangle gives a segment, densified"""
        y = T[:, :, 1] - Yt
        s = np.sign(y)
        m = ~((s[:, 0] == s[:, 1]) & (s[:, 1] == s[:, 2]))
        if not m.any():
            return np.zeros((0, 2))
        Tm, ym = T[m], y[m]
        ends = []
        for a, b in ((0, 1), (1, 2), (2, 0)):
            ya, yb = ym[:, a], ym[:, b]
            c = (ya * yb) < 0
            t = np.where(c, ya / np.where(c, ya - yb, 1), 0)[:, None]
            P = Tm[:, a] + (Tm[:, b] - Tm[:, a]) * t
            ends.append((c, P[:, [0, 2]]))
        segs = []
        for (c1, P1), (c2, P2) in ((ends[0], ends[1]), (ends[1], ends[2]), (ends[2], ends[0])):
            k = c1 & c2
            if k.any():
                segs.append((P1[k], P2[k]))
        if not segs:
            return np.zeros((0, 2))
        A = np.concatenate([a for a, _ in segs]); B = np.concatenate([b for _, b in segs])
        t = np.linspace(0, 1, dens)[None, :, None]
        return (A[:, None, :] + (B - A)[:, None, :] * t).reshape(-1, 2)

    def section(self, part, y, x0, x1, u, s_row=None):
        key = "torso" if part == "torso" else (None if part[0] in "uf" else part[1])
        if key is None:                         # arms: round (template arms are in a T-pose)
            w = min(float(x1 - x0 + 1), 1.15 * self.g.get("arm_w_" + part, 1e9))
            e = np.sqrt(np.clip(1 - u * u, 0, 1))
            return self.g["arm_z"] + 0.5 * w * e, self.g["arm_z"] - 0.5 * w * e
        c, zf, zb, xc, hw = self._slice(key, self.Yt(y))
        w = float(x1 - x0 + 1)
        s = s_row if s_row is not None else min(1.5 * self.S, max(0.7 * self.S, 0.5 * w / hw))
        zfu = np.interp(u, c, zf); zbu = np.interp(u, c, zb)
        zm = 0.5 * (zfu + zbu)
        # offsets (posture: chest forward, bottom back, head forward) at the global scale, shape at the row scale
        zoff = zm * self.S
        return zoff + (zfu - zm) * s, zoff + (zbu - zm) * s

    def row_scale(self, part, y, x0, x1):
        key = "torso" if part == "torso" else (None if part[0] in "uf" else part[1])
        if key is None:
            return None
        c, zf, zb, xc, hw = self._slice(key, self.Yt(y))
        return 0.5 * (x1 - x0 + 1) / hw


# ------------------------------------------------------------------ side photo fit
def side_profile(side_rgba, stand_h, faces="right"):
    """side cut-out -> per-row (front, back) x extents relative to the body axis, scaled to stand_h rows"""
    a = np.asarray(side_rgba.convert("RGBA"))
    al = a[..., 3] > 128
    rows = np.nonzero(al.any(1))[0]
    if len(rows) < 10:
        raise ValueError("side photo: no person found (give a cut-out PNG or a photo the cutout can find)")
    top, bot = rows.min(), rows.max()
    sc = stand_h / float(bot - top + 1)
    crop = side_rgba.crop((0, top, side_rgba.width, bot + 1))
    crop = crop.resize((max(1, int(round(side_rgba.width * sc))), int(stand_h)), Image.LANCZOS)
    if faces == "left":
        crop = crop.transpose(Image.FLIP_LEFT_RIGHT)
    a = np.asarray(crop)
    al = a[..., 3] > 128
    front = np.full(al.shape[0], np.nan); back = np.full(al.shape[0], np.nan)
    for y in range(al.shape[0]):
        xs = np.nonzero(al[y])[0]
        if len(xs):
            front[y] = xs.max(); back[y] = xs.min()
    # body axis: middle of the legs over the lower body (ankle .. knee rows)
    lo = slice(int(0.55 * len(front)), int(0.92 * len(front)))
    axis = np.nanmedian(0.5 * (front[lo] + back[lo]))
    return dict(front=front - axis, back=back - axis, rgb=_edge_fixed_rgb(a), axis=axis, img=a)


