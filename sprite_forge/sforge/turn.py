def _lm_part(i):
    k = "n" if i % 2 == 1 else "f"
    if i <= 10:
        return "torso"
    if i in (11, 12, 13, 14):
        return "u" + k
    if i <= 22:
        return "f" + k
    if i in (23, 24):
        return "t" + k
    return "s" + k


def project_landmarks(res, landmarks):
    """the 33 pose landmarks moved to where the turned view draws them (z from the part's own cross-sections);
    when the view shows the back, left/right labels are swapped so 'left' is image-right again (as the front
    puppet expects)"""
    out = []
    for i, (x, y, v) in enumerate(landmarks):
        try:
            X, Y = res.scr((x, y), _lm_part(i))
        except Exception:
            X, Y = res.scr((x, y), "torso")
        out.append([float(X), float(Y), v])
    if math.cos(math.radians(res.yaw)) < 0:
        for a, b in _PAIRS:
            out[a], out[b] = out[b], out[a]
    return out


def mirror_turned(res):
    """flip a turned result left-right (a 270-degree turn faces image-left; fighter sprites face right)"""
    W, H = res.size
    res.layers = {k: v.transpose(Image.FLIP_LEFT_RIGHT) for k, v in res.layers.items()}
    res.joints = {k: {n: (W - 1 - p[0], p[1]) for n, p in d.items()} for k, d in res.joints.items()}
    res.composite = res.composite.transpose(Image.FLIP_LEFT_RIGHT)
    old = res.scr
    res.scr = lambda p, part, _o=old: (W - 1 - _o(p, part)[0], _o(p, part)[1])
    res.mirrored = True
    return res


def is_side(yaw):
    return abs(math.sin(math.radians(yaw))) > 0.5


def make_rig(res, landmarks):
    """side-on views -> SideRig (+ side_move_keys); near-front / back views -> the front puppet Rig on the
    turned image with projected landmarks (+ puppet.move_keys)"""
    if is_side(res.yaw):
        return SideRig(res)
    from .puppet import Rig
    return Rig(res.composite, project_landmarks(res, landmarks))


