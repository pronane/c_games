def turn_args(spec):
    """'90' | 'side' | 'left' | 'back' | '0' -> yaw degrees"""
    s = str(spec).strip().lower()
    named = {"front": 0, "side": 90, "right": 90, "profile": 90, "back": 180, "left": 270}
    return float(named[s]) if s in named else float(s)


