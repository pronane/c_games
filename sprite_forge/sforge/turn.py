def parse_params(spec):
    """'gender=1,age=0.55,muscle=0.5,weight=0.55' -> dict (None if empty)"""
    if not spec:
        return None
    out = {}
    for kv in str(spec).split(","):
        if "=" in kv:
            k, v = kv.split("=", 1)
            try:
                out[k.strip()] = float(v)
            except ValueError:
                out[k.strip()] = v.strip()
    return out or None
