def geometry(rig, h0, w0):
    """body heights / landmarks (cut-out coords) used by the depth models"""
    pad, padt = rig.pad, rig.padt
    J = {k: {n: (p[0] - pad, p[1] - padt) for n, p in v.items()} for k, v in rig.J.items()}
    L = [(x - pad, y - padt) for x, y in rig.L]
    top, ground = rig.top - padt, rig.ground - padt
    H = ground - top + 1
    sh = 0.5 * (J["n"]["S"][1] + J["f"]["S"][1])
    hip = 0.5 * (J["n"]["P"][1] + J["f"]["P"][1])
    mouth = 0.5 * (L[9][1] + L[10][1])
    chin = mouth + 0.35 * (sh - mouth)
    g = dict(top=top, ground=ground, stand_h=H, shoulder=sh, hip=hip, chin=chin, neck=chin + 0.45 * (sh - chin),
             chest=sh + 0.18 * (hip - sh), waist=sh + 0.62 * (hip - sh), crotch=rig.crotch - padt,
             ankle={"n": J["n"]["A"][1], "f": J["f"]["A"][1]}, knee_m=0.5 * (J["n"]["K"][1] + J["f"]["K"][1]),
             ankle_m=0.5 * (J["n"]["A"][1] + J["f"]["A"][1]), hip_m=hip, arm_z=0.0, J=J)
    return g


def clean_hand_mask(m, J, L, k, others=None, pad=(0, 0)):
    """visible hand: keep a compact hand (drops fingers of another person held in it); fixes 'child's fingers'"""
    W_ = J[k]["W"]; ids = (17, 19, 21) if k == "n" else (18, 20, 22)
    pts = np.array([L[i] for i in ids], float)
    hc = (np.array(W_) + pts.mean(0)) / 2
    R = 1.2 * max(np.hypot(*(pts - hc).T).max(), np.hypot(*(np.array(W_) - hc))) + 4
    H, Wd = m.shape
    yy, xx = np.mgrid[0:H, 0:Wd]
    E_ = J[k]["E"]
    d = np.array(W_, float) - np.array(E_, float); d /= max(1e-6, np.hypot(*d))
    beyond = ((xx - W_[0]) * d[0] + (yy - W_[1]) * d[1]) > 0
    far = (xx - hc[0]) ** 2 + (yy - hc[1]) ** 2 > R * R
    out = m & ~(beyond & far)
    if others is not None:
        out &= ~ndi.binary_dilation(others, iterations=3)
    lab, n = ndi.label(out)
    if n > 1:
        sizes = ndi.sum(out, lab, range(1, n + 1))
        out = lab == (1 + int(np.argmax(sizes)))
    return out, int((m & ~out).sum())


def build_turned(cut, landmarks, yaw=90.0, depth="auto", side=None, side_faces="right", template_params=None,
                 clean_hand=True, others_mask=None, far_shade=0.82, balance=0.9, log=print):
    from .puppet import Rig
    cut = cut.convert("RGBA")
    rig = Rig(cut, landmarks)
    A0 = np.asarray(cut)
    h0, w0 = A0.shape[:2]
    pad, padt = rig.pad, rig.padt
    crop = lambda m: m[padt:padt + h0, pad:pad + w0]
    g = geometry(rig, h0, w0)
    L = [(x - pad, y - padt) for x, y in rig.L]
    # ---- part masks + textures (cut-out coords)
    masks = {}
    tex = _edge_fixed_rgb(A0)
    solid = A0[..., 3] > 127
    for k in ("n", "f"):
        masks["u" + k] = crop(rig.pieces["u" + k])
        # a hidden hand (pocket): only the sleeve moves with the arm, the pocket stays on the body
        masks["f" + k] = crop(rig.pieces["f" + k])
        masks["t" + k] = crop(rig.pieces["t" + k])
        masks["s" + k] = crop(rig.pieces["s" + k])
    removed = 0
    if clean_hand:
        vis = rig.hand_visible
        oth = None
        if others_mask is not None:
            oth = np.asarray(others_mask.convert("L").resize((w0, h0))) > 127
        before = masks["f" + vis] & solid
        masks["f" + vis], removed = clean_hand_mask(masks["f" + vis], g["J"], L, vis, oth)
        solid = solid & ~(before & ~masks["f" + vis])        # dropped pixels are gone (not body either)
        if removed:
            log("turn: visible hand cleaned (%d px of another person's fingers / stray pixels removed)" % removed)
    for k in masks:
        masks[k] = masks[k] & solid
    # body = everything that is not a limb; where an arm covered the body in the photo, the gap (inside the
    # body outline of that row) is filled from the nearest body pixels
    legs = masks["tn"] | masks["sn"] | masks["tf"] | masks["sf"]
    arms = masks["un"] | masks["fn"] | masks["uf"] | masks["ff"]
    body = solid & ~legs & ~arms
    gap = np.zeros_like(body)
    for y in np.nonzero(body.any(1))[0]:
        xs = np.nonzero(body[y])[0]
        if len(xs) > 1:
            seg = np.zeros(w0, bool); seg[xs.min():xs.max() + 1] = True
            gap[y] = seg & arms[y] & ~body[y]
    if clean_hand:      # pixels dropped from the hand never come back as body
        gap &= ~(crop(rig.pieces["f" + rig.hand_visible]) & solid & ~masks["f" + rig.hand_visible])
    body_tex = tex.copy()
    if gap.any():
        _, (iy, ix) = ndi.distance_transform_edt(~body, return_indices=True)
        fill = tex[iy, ix].astype(np.float32)
        sm = np.stack([ndi.gaussian_filter(fill[..., c], 5) for c in range(3)], -1)
        body_tex[gap] = sm[gap].clip(0, 255).astype(np.uint8)
    masks["torso"] = body | gap
    torso_tex = body_tex
    # ---- depth model
    src = depth
    if depth in ("auto", "side"):
        from . import human
        src = "template" if human.have_assets() else "relief"
    if src == "template":
        model = Template(g, template_params, log=log)
    else:
        model = Relief(g)
        log("turn: depth = procedural relief (ellipse sections%s)" % ("" if depth == "relief" else "; MakeHuman template not installed: forge.py human --setup"))
    # arms hang at the torso's mid depth at shoulder height
    xs_ = np.nonzero(masks["torso"][int(g["chest"])])[0]
    if len(xs_):
        u = np.linspace(-0.9, 0.9, 9)
        zf, zb = (model.section("torso", g["chest"], xs_.min(), xs_.max(), u) if src == "relief"
                  else model.section("torso", g["chest"], xs_.min(), xs_.max(), u))
        g["arm_z"] = float(np.mean(0.5 * (zf + zb))) - 0.01 * g["stand_h"]
    # ---- row cross-sections
    cx = 0.25 * sum(g["J"][k][n][0] for k in ("n", "f") for n in ("S", "P"))
    sections = {}       # part -> list of (y, x0, x1, xs, zf, zb)
    for part in PART_NAMES:
        m = masks[part]
        rows = np.nonzero(m.any(1))[0]
        lst = []
        for y in rows:
            for x0, x1 in _runs(m[y]):
                if x1 - x0 < 1 and part != "torso":
                    continue
                lst.append([y, x0, x1])
        if part[0] in "uf" and lst:      # arm depth: no thicker than the arm itself (shoulder rows are wide)
            wmed = float(np.median([x1 - x0 + 1 for _, x0, x1 in lst]))
            g["arm_w_" + part] = wmed
        if src == "template" and part[0] not in "uf" and lst:
            s = np.array([model.row_scale(part, y, x0, x1) for y, x0, x1 in lst], float)
            S = model.S
            s = np.clip(ndi.gaussian_filter1d(s, 6, mode="nearest"), 0.7 * S, 1.5 * S)
        else:
            s = [None] * len(lst)
        out = []
        for (y, x0, x1), sr in zip(lst, s):
            n = int((x1 - x0 + 1) * SS_SAMPLES) + 2
            xs = np.linspace(x0 - 0.5, x1 + 0.5, n)
            u = np.clip((xs - (x0 + x1) / 2) / max(0.5, (x1 - x0 + 1) / 2), -1, 1)
            if src == "template":
                zf, zb = model.section(part, y, x0, x1, u, sr)
            else:
                zf, zb = model.section(part, y, x0, x1, u)
            out.append((y, x0, x1, xs, np.asarray(zf, float), np.asarray(zb, float)))
        sections[part] = out
    # ---- side photo fit
    side_info = None
    if side is not None:
        sp = side_profile(side, g["stand_h"], side_faces)
        nrow = len(sp["front"])
        ext = {}
        for part, lst in sections.items():
            for y, x0, x1, xs, zf, zb in lst:
                e = ext.setdefault(y, [1e9, -1e9]); e[0] = min(e[0], zb.min()); e[1] = max(e[1], zf.max())
        fitted = 0
        newsec = {}
        for part, lst in sections.items():
            nl = []
            for y, x0, x1, xs, zf, zb in lst:
                r = int(round(y - g["top"]))
                if 0 <= r < nrow and not np.isnan(sp["front"][r]):
                    lo, hi = ext[y]
                    F_, B_ = sp["front"][r], sp["back"][r]
                    if hi - lo > 2 and F_ - B_ > 2:
                        k_ = (F_ - B_) / (hi - lo)
                        zf = B_ + (zf - lo) * k_; zb = B_ + (zb - lo) * k_
                        fitted += 1
                nl.append((y, x0, x1, xs, zf, zb))
            newsec[part] = nl
        sections = newsec
        side_info = sp
        log("turn: side photo fitted: %d row sections matched to the side silhouette" % fitted)
    # back colour per part: the part's own edge colours, blended across, smoothed vertically
    back = {}
    for part, lst in sections.items():
        acc = np.zeros((h0, w0, 3), np.float32); wt = np.zeros((h0, w0), np.float32)
        T = torso_tex if part == "torso" else tex
        for y, x0, x1, xs, zf, zb in lst:
            w = x1 - x0 + 1
            band = max(3, int(0.22 * w))
            ins = max(1, int(0.06 * w)) if w > 12 else 0
            cl = np.median(T[y, x0 + ins:x0 + ins + band].reshape(-1, 3), 0)
            cr = np.median(T[y, x1 - ins - band + 1:x1 - ins + 1].reshape(-1, 3), 0)
            # the side/back is never lit brighter than this row's own front average
            rm = np.median(T[y, x0:x1 + 1].reshape(-1, 3), 0); lm = rm.mean() * 1.05 + 1
            cl = cl * min(1.0, lm / max(1, cl.mean())); cr = cr * min(1.0, lm / max(1, cr.mean()))
            t = np.linspace(0, 1, w)[:, None]
            acc[y, x0:x1 + 1] = cl * (1 - t) + cr * t
            wt[y, x0:x1 + 1] = 1
        if part == "torso":       # head: the back of the head gets the crown's colour (scalp / hair), not ears or face
            top, chin = int(g["top"]), int(g["chin"])
            crown = masks["torso"][top:top + max(4, int(0.25 * (chin - top)))]
            cc = T[top:top + crown.shape[0]][crown]
            if len(cc):
                crown_col = np.median(cc.reshape(-1, 3), 0)
                for y in range(top, min(h0, chin + 1)):
                    k_ = np.clip((y - top) / max(1.0, chin - top) - 0.55, 0, 1) / 0.45   # towards the neck: edge colours
                    row = wt[y] > 0
                    acc[y, row] = crown_col * (1 - k_) + acc[y, row] * k_
        num = np.stack([ndi.gaussian_filter(acc[..., c] * 1.0, (12, 3)) for c in range(3)], -1)
        den = ndi.gaussian_filter(wt, (12, 3))[..., None]
        bb = np.where(den > 1e-3, num / np.maximum(den, 1e-3), acc)
        back[part] = bb * 0.9           # the back is a touch darker (it faces away from the light)
    # ---- render each part turned
    th = math.radians(yaw)
    ct, st = math.cos(th), math.sin(th)
    span = 0
    for lst in sections.values():
        for y, x0, x1, xs, zf, zb in lst:
            span = max(span, abs(x0 - cx), abs(x1 - cx), np.abs(zf).max(), np.abs(zb).max())
    Wout = int(2 * span + 40)
    xoff = Wout / 2.0
    layers, zmean = {}, {}
    for part, lst in sections.items():
        T = torso_tex if part == "torso" else tex
        img, zm = _render_part(lst, T, back[part], ct, st, cx, xoff, Wout, h0,
                               side_info, g, near_sign=(1 if yaw % 360 < 180 else -1))
        layers[part] = img; zmean[part] = zm
    # lighting balance: a side view shows the photo's edge columns (one of them often sun-lit, the other in
    # shade) stretched across the side of the body; pull each garment's turned colour back towards the
    # garment's average in the photo (gain only, so logos/folds keep their contrast)
    if abs(st) > 0.3 and balance > 0:
        groups = {"arms": ("un", "fn", "uf", "ff"), "legs": ("tn", "sn", "tf", "sf")}
        for gname, parts in groups.items():
            gm = np.zeros((h0, w0), bool)
            for p_ in parts:
                gm |= masks[p_]
            if gm.sum() < 50:
                continue
            tgt = np.median(tex[gm].reshape(-1, 3).astype(np.float32), 0)
            for p_ in parts:
                layers[p_] = _balance(layers[p_], tgt, balance)
        # torso below the chin (the head keeps its own colours)
        tm = masks["torso"].copy(); tm[:int(g["chin"]) + 1] = False
        if tm.sum() > 50:
            layers["torso"] = _balance(layers["torso"], np.median(torso_tex[tm].reshape(-1, 3).astype(np.float32), 0),
                                       balance, y0=int(g["chin"]) + 1)
    # near / far (towards the camera / away) and joints on screen
    def scr(p, part):
        X = p[0] - cx
        Z = _part_zc(sections[part], p[1])
        return (X * ct + Z * st + xoff, p[1])
    Js = {}
    for k in ("n", "f"):
        j = g["J"][k]
        Js[k] = dict(S=scr(j["S"], "u" + k), E=scr(j["E"], "u" + k), W=scr(j["W"], "f" + k), T=scr(j["T"], "f" + k),
                     P=scr(j["P"], "t" + k), K=scr(j["K"], "s" + k), A=scr(j["A"], "s" + k),
                     toe=scr(j["toe"], "s" + k), heel=scr(j["heel"], "s" + k))
    # which front-rig side is nearer the camera after the turn
    zn = np.mean([zmean[p] for p in ("un", "fn", "tn", "sn") if zmean[p] is not None])
    zf_ = np.mean([zmean[p] for p in ("uf", "ff", "tf", "sf") if zmean[p] is not None])
    near = "n" if zn > zf_ else "f"
    res = Turned()
    res.layers, res.joints, res.yaw, res.depth = layers, Js, yaw, (src + ("+side" if side is not None else ""))
    res.near = near
    res.cx = scr((cx, 0), "torso")[0] if False else xoff + 0.0
    res.size = (Wout, h0)
    res.geo = g
    res.hand_removed = removed
    res.rig_front = rig
    res.far_shade = far_shade
    res.composite = composite_layers(res)
    res.scr = scr
    return res


def _balance(L, target, k, y0=0):
    """per-channel gain so the layer's mean colour (rows >= y0) moves a fraction k towards target"""
    a = np.asarray(L).astype(np.float32)
    m = a[..., 3] > 200
    m[:y0] = False
    if m.sum() < 30:
        return L
    cur = np.median(a[m][:, :3], 0)
    gain = np.clip((np.maximum(target, 1) / np.maximum(cur, 1)) ** k, 0.5, 1.25)
    sel = np.zeros(a.shape[:2], bool); sel[y0:] = True; sel &= a[..., 3] > 0
    if y0 > 0:      # feather the seam at the chin over 12 rows
        ramp = np.clip((np.arange(a.shape[0]) - y0 + 12) / 12.0, 0, 1)[:, None, None]
    else:
        ramp = 1.0
    g_ = 1 + (gain[None, None, :] - 1) * ramp
    a[..., :3] = np.where((a[..., 3:4] > 0), a[..., :3] * g_, a[..., :3])
    return Image.fromarray(a.clip(0, 255).astype(np.uint8), "RGBA")


def _part_zc(lst, y):
    best = None
    for yy, x0, x1, xs, zf, zb in lst:
        if best is None or abs(yy - y) < abs(best[0] - y):
            best = (yy, 0.5 * (float(np.mean(zf)) + float(np.mean(zb))))
    return best[1] if best else 0.0


def _render_part(lst, T, B, ct, st, cx, xoff, Wout, H, side_info, g, near_sign=1):
    """rasterise every cross-section loop (front sheet = photo, back sheet = edge colour), z-buffered"""
    WS = Wout * SS_X
    P_x, P_y, P_z, P_c, P_s = [], [], [], [], []
    for y, x0, x1, xs, zf, zb in lst:
        n = len(xs)
        X = np.concatenate([xs, xs[::-1]]) - cx
        Z = np.concatenate([zf, zb[::-1]])
        xi = np.clip(np.round(xs).astype(int), x0, x1)
        cf = T[y, xi].astype(np.float32)
        cb = B[y, xi].astype(np.float32)
        uu = np.abs((xs - (x0 + x1) / 2) / max(0.5, (x1 - x0 + 1) / 2))
        wseam = np.clip((uu - 0.80) / 0.2, 0, 1)[:, None] * 0.6
        cf = cf * (1 - wseam) + cb / 0.9 * wseam
        C = np.concatenate([cf, cb[::-1]])
        isf = np.concatenate([np.ones(n, bool), np.zeros(n, bool)])
        # closed loop
        X = np.append(X, X[0]); Z = np.append(Z, Z[0]); C = np.vstack([C, C[:1]]); isf = np.append(isf, True)
        # normals (outward) from the loop tangent
        tX = np.gradient(X); tZ = np.gradient(Z)
        nl = np.hypot(tX, tZ) + 1e-9
        nX, nZ = -tZ / nl, tX / nl
        xp = (X * ct + Z * st + xoff) * SS_X
        zp = -X * st + Z * ct
        nzr = -nX * st + nZ * ct
        # the photo already carries its own front lighting: relight relative to it, never brighter than the photo
        shade = np.where(isf, (0.72 + 0.28 * np.clip(nzr, 0, 1)) / (0.72 + 0.28 * np.clip(nZ, 0, 1)),
                         (0.72 + 0.28 * np.clip(nzr, 0, 1)))
        shade = np.clip(shade, 0.55, 1.0)
        if side_info is not None:
            r = int(round(y - g["top"]))
            img = side_info["rgb"]
            if 0 <= r < img.shape[0]:
                sx = np.clip(np.round(Z + side_info["axis"]).astype(int), 0, img.shape[1] - 1)
                al = side_info["img"][r, sx, 3] > 128
                wside = np.clip((np.abs(nX) - 0.35) / 0.4, 0, 1) * al
                C = C * (1 - wside[:, None]) + img[r, sx].astype(np.float32) * wside[:, None]
        # polyline fill between consecutive samples
        dx = np.abs(np.diff(xp))
        cnt = np.ceil(dx).astype(int) + 1
        idx = np.repeat(np.arange(len(xp) - 1), cnt)
        off = np.cumsum(cnt) - cnt
        t = (np.arange(cnt.sum()) - off[idx]) / cnt[idx]
        px = xp[idx] + (xp[idx + 1] - xp[idx]) * t
        pz = zp[idx] + (zp[idx + 1] - zp[idx]) * t
        pc = C[idx] + (C[idx + 1] - C[idx]) * t[:, None]
        ps = shade[idx] + (shade[idx + 1] - shade[idx]) * t
        P_x.append(px); P_z.append(pz); P_c.append(pc); P_s.append(ps); P_y.append(np.full(len(px), y))
    out = np.zeros((H, WS, 4), np.float32)
    if not P_x:
        return Image.new("RGBA", (Wout, H), (0, 0, 0, 0)), None
    px = np.concatenate(P_x); py = np.concatenate(P_y); pz = np.concatenate(P_z)
    pc = np.concatenate(P_c); ps = np.concatenate(P_s)
    ix = np.clip(np.round(px).astype(int), 0, WS - 1)
    key = py.astype(np.int64) * WS + ix
    order = np.lexsort((pz, key))
    key_s = key[order]
    last = np.r_[key_s[1:] != key_s[:-1], True]
    sel = order[last]
    out_flat = out.reshape(-1, 4)
    out_flat[key[sel], :3] = pc[sel] * ps[sel, None]
    out_flat[key[sel], 3] = 255
    # supersampled -> final width (box filter)
    o = out.reshape(H, Wout, SS_X, 4)
    a = o[..., 3].mean(2)
    rgb = (o[..., :3] * o[..., 3:4]).sum(2) / np.maximum(o[..., 3].sum(2)[..., None], 1e-6)
    res = np.dstack([rgb, a]).clip(0, 255).astype(np.uint8)
    return Image.fromarray(res, "RGBA"), float(np.mean(pz))


def composite_layers(res, shade_far=True):
    """turned rest pose: far limbs, far leg, torso, near leg, near limbs"""
    near, far = res.near, ("f" if res.near == "n" else "n")
    W, H = res.size
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    fs = res.far_shade if shade_far else 1.0
    def put(name, k=1.0):
        L = res.layers[name]
        if k != 1.0:
            L = darken(L, k)
        im.alpha_composite(L)
    side_on = abs(math.sin(math.radians(res.yaw))) > 0.5
    if side_on:
        for p in ("u", "f"):
            put(p + far, fs)
        for p in ("t", "s"):
            put(p + far, fs)
        put("torso")
        for p in ("t", "s"):
            put(p + near)
        for p in ("u", "f"):
            put(p + near)
    else:
        for p in ("t", "s"):
            put(p + far); put(p + near)
        put("torso")
        for p in ("u", "f"):
            put(p + far); put(p + near)
    return im


def darken(L, k):
    a = np.asarray(L).copy()
    a[..., :3] = (a[..., :3].astype(np.float32) * k).clip(0, 255).astype(np.uint8)
    return Image.fromarray(a, "RGBA")


# ======================================================================== side-on puppet
class SideRig:
    """photo puppet from a TURNED model: one layer per part (side 'n' = nearer the camera), same pose language
    as sforge.puppet (segment directions in degrees from 'down', +90 = forwards = image right)."""

    def __init__(self, res, pad_frac=0.75):
        from . import puppet as PP
        self.PP = PP
        W0, H0 = res.size
        self.pad = pad = int(H0 * pad_frac)
        self.padt = padt = int(H0 * 0.45)
        H, W = H0 + padt + 8, W0 + 2 * pad
        self.shape = (H, W)
        far_src = "f" if res.near == "n" else "n"
        src = {"n": res.near, "f": far_src}
        self.src = src
        fs = res.far_shade
        def padded(im, k=1.0):
            c = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            c.paste(darken(im, k) if k != 1.0 else im, (pad, padt))
            return c
        lay = {"torso": padded(res.layers["torso"])}
        for k in ("n", "f"):
            sh = 1.0 if k == "n" else fs
            for p in ("u", "f", "t", "s"):
                lay[p + k] = padded(res.layers[p + src[k]], sh)
        J = {}
        for k in ("n", "f"):
            J[k] = {nm: (p[0] + pad, p[1] + padt) for nm, p in res.joints[src[k]].items()}
        self.J = J
        comp = padded(res.composite)
        a = np.asarray(comp)
        alpha = a[..., 3] > 40
        rows = np.nonzero(alpha.any(1))[0]
        self.top, self.ground = int(rows.min()), int(rows.max())
        self.stand_h = self.ground - self.top + 1
        self.cx = 0.5 * (J["n"]["P"][0] + J["f"]["P"][0])
        sh_ = self.stand_h
        self.r_leg, self.r_arm = 0.055 * sh_, 0.036 * sh_
        def arr(im):
            return np.asarray(im)
        def cap(name, layers, c, r):
            m = np.zeros((H, W, 4), np.uint8)
            for nm in layers:
                L = arr(lay[nm]); sel = L[..., 3] > 0
                m[sel] = L[sel]
            yy, xx = np.ogrid[0:H, 0:W]
            d = (xx - c[0]) ** 2 + (yy - c[1]) ** 2 <= r * r
            m[~d] = 0
            lay[name] = Image.fromarray(m, "RGBA")
        for k in ("n", "f"):
            cap("t%s_cap" % k, ["t" + k], J[k]["P"], self.r_leg * 1.05)
            cap("s%s_cap" % k, ["t" + k, "s" + k], J[k]["K"], self.r_leg * 0.85)
            cap("u%s_cap" % k, ["u" + k], J[k]["S"], self.r_arm * 1.2)
            cap("f%s_cap" % k, ["u" + k, "f" + k], J[k]["E"], self.r_arm * 0.9)
            lay["f%s_full" % k] = lay["f" + k]
        # hidden hand (in a pocket in the photo): a copy of the other hand, as seen from the same side
        self.fist = {}
        hid_front = res.rig_front.hand_hidden if res.rig_front.fist else None
        if hid_front:
            kh = "n" if src["n"] == hid_front else "f"
            kv = "f" if kh == "n" else "n"
            Lv = arr(lay["f" + kv]).copy()
            E_, W_ = np.array(J[kv]["E"]), np.array(J[kv]["W"])
            d = (W_ - E_) / max(1e-6, np.hypot(*(W_ - E_)))
            yy, xx = np.mgrid[0:H, 0:W]
            beyond = ((xx - W_[0]) * d[0] + (yy - W_[1]) * d[1]) > -0.01 * sh_
            Lv[~beyond] = 0
            hand = Image.fromarray(Lv, "RGBA")
            if kh == "f":
                hand = darken(hand, fs)
            Wh, Eh = J[kh]["W"], J[kh]["E"]
            theta = PP._dir(Eh, Wh) - PP._dir(J[kv]["E"], J[kv]["W"])
            M = PP._tr(Wh[0] - W_[0], Wh[1] - W_[1]) @ PP._rot(theta, tuple(W_))
            self.fist[kh] = hand.transform((W, H), Image.AFFINE, tuple(np.linalg.inv(M)[:2].ravel()), resample=Image.BICUBIC)
            lay["f%s_fist" % kh] = self.fist[kh]
            self.hand_hidden_side = kh
        self._layers = lay
        self._bbox = {}
        d_ = PP._dir
        self.rest = {"un": d_(J["n"]["S"], J["n"]["E"]), "fn": d_(J["n"]["E"], J["n"]["T"]),
                     "uf": d_(J["f"]["S"], J["f"]["E"]), "ff": d_(J["f"]["E"], J["f"]["T"]),
                     "tn": d_(J["n"]["P"], J["n"]["K"]), "sn": d_(J["n"]["K"], J["n"]["A"]),
                     "tf": d_(J["f"]["P"], J["f"]["K"]), "sf": d_(J["f"]["K"], J["f"]["A"])}
        self.A = a
        self.res = res
        self.side = True

    def layer(self, name):
        return self._layers[name]

    _warp = None  # set below

    def render(self, pose):
        """like puppet.Rig.render, side-on draw order: far arm, far leg, body, near leg, near arm"""
        PP = self.PP
        J, rest = self.J, self.rest
        pelvis = ((J["n"]["P"][0] + J["f"]["P"][0]) / 2, (J["n"]["P"][1] + J["f"]["P"][1]) / 2)
        M0 = PP._rot(-pose.get("lean", 0.0), pelvis) @ PP._scale(pose.get("sx", 1.0), pose.get("sy", 1.0), pelvis)
        def chain(k, a, b, ja, jb, jc, base):
            d1 = pose.get(a, rest[a]) - rest[a]
            d2 = (pose[b] - rest[b]) if b in pose else d1
            R1 = PP._rot(d1, J[k][ja])
            j2 = PP._ap(R1, J[k][jb])
            M1 = base @ R1
            M2 = base @ PP._tr(j2[0] - J[k][jb][0], j2[1] - J[k][jb][1]) @ PP._rot(d2, J[k][jb])
            return M1, M2, PP._ap(M2, J[k][jc])
        H, W = self.shape
        canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        I = np.eye(3)
        hands = {}
        def leg(k):
            Mt, Ms, foot = chain(k, "t" + k, "s" + k, "P", "K", "A", I)
            for nm, M in (("s" + k, Ms), ("t" + k + "_cap", Mt), ("t" + k, Mt), ("s" + k + "_cap", Ms)):
                self._warp(nm, M, canvas)
        def arm(k):
            Mu, Mf, tip = chain(k, "u" + k, "f" + k, "S", "E", "T", M0)
            seq = [("u" + k, Mu), ("u" + k + "_cap", Mu), ("f" + k, Mf), ("f" + k + "_cap", Mf)]
            if k in self.fist:
                seq.append(("f" + k + "_fist", Mf))
            for nm, M in seq:
                self._warp(nm, M, canvas)
            hands[k] = PP._ap(Mf, J[k]["W"]), tip
        # legs are not leaned with the body (they carry it); the body leans about the pelvis
        arm("f"); leg("f")
        self._warp("torso", M0, canvas)
        leg("n"); arm("n")
        a = np.asarray(canvas)
        rows = np.nonzero((a[..., 3] > 40).any(1))[0]
        low = int(rows.max()) if len(rows) else self.ground
        dy = self.ground - low - pose.get("lift", 0.0) * self.stand_h
        dx = pose.get("dx", 0.0) * self.stand_h
        out = canvas.transform(canvas.size, Image.AFFINE, (1, 0, -dx, 0, 1, -dy), resample=Image.BICUBIC)
        if pose.get("tint"):
            r, g_, b, k = pose["tint"]
            arr = np.asarray(out).astype(np.float32)
            m = arr[..., 3] > 0
            arr[m, :3] = arr[m, :3] * (1 - k) + np.array([r, g_, b]) * k
            out = Image.fromarray(arr.clip(0, 255).astype(np.uint8), "RGBA")
        fx = []
        self.last_hands = {k: ((w_[0] + t_[0]) / 2 + dx, (w_[1] + t_[1]) / 2 + dy) for k, (w_, t_) in hands.items()}
        for k in pose.get("glow_hands", ""):
            fx.append(("glow", self.last_hands[k], pose.get("glow", (120, 200, 255)), 0.06 * self.stand_h))
        if pose.get("orb"):
            ks = pose.get("orb_hand", "n")
            pts = [hands[k][1] for k in ks]
            c = (sum(p[0] for p in pts) / len(pts) + dx + pose.get("orb_ahead", 0.03) * self.stand_h,
                 sum(p[1] for p in pts) / len(pts) + dy)
            fx.append(("orb", c, pose["orb"], pose.get("orb_r", 0.05) * self.stand_h))
        for kind, c, col, r in fx:
            out = PP._effect(out, kind, c, col, r)
        return out


def _side_warp(self, name, M, canvas):
    from .puppet import Rig
    return Rig._warp(self, name, M, canvas)


SideRig._warp = _side_warp


