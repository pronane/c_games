def parse_colour(v, table=COLOURS, default=(0.5, 0.5, 0.5)):
    if v is None or v == "":
        return default
    if isinstance(v, tuple):
        return v
    s = str(v).strip().lower().replace(" ", "_").replace("-", "_")
    if s.startswith("#") and len(s) in (4, 7):
        if len(s) == 4:
            s = "#" + "".join(c * 2 for c in s[1:])
        return tuple(int(s[i:i + 2], 16) / 255 for i in (1, 3, 5))
    if "," in s:
        p = [float(x) for x in s.split(",")]
        return tuple(x / 255 if max(p) > 1 else x for x in p[:3])
    for t in (table, COLOURS):
        if s in t:
            return t[s]
    return default


@dataclass
class CharacterSpec:
    name: str = "character"
    height_cm: float = 180.0
    weight_kg: float = 75.0
    build: str = "athletic"
    skin_tone: str = "medium"
    ethnicity: str = ""          # metadata only - set skin_tone explicitly
    complexion: str = ""         # metadata, or 'freckles' adds freckle dots
    hair_colour: str = "dark_brown"
    hair_style: str = "short"    # bald buzz short long ponytail curly afro bun
    facial_hair: str = "none"    # none stubble beard moustache
    eye_colour: str = "brown"
    nose: str = "medium"
    ears: str = "medium"
    mouth: str = "medium"
    hands: str = "medium"
    feet: str = "medium"
    head: str = "medium"
    top: str = "jersey"          # jersey tshirt longsleeve tank hoodie
    top_colour: str = ""
    trim_colour: str = ""
    bottom: str = "shorts"       # shorts trousers
    bottom_colour: str = ""
    socks_colour: str = ""
    shoes: str = "boots"         # boots trainers barefoot
    shoes_colour: str = ""
    kit: str = "home"            # home away blue red black gk  (fallback colours)
    extra: dict = field(default_factory=dict)

    # ---- derived numbers used by the mesh builder
    @property
    def scale(self):
        return max(0.5, min(1.4, float(self.height_cm) / 180.0))

    @property
    def girth(self):
        g = BUILDS.get(self.build.lower(), 1.0)
        h = float(self.height_cm) / 100.0
        bmi = float(self.weight_kg) / max(0.5, h * h)
        g *= max(0.82, min(1.4, (bmi / 23.0) ** 0.5))
        return g

    def size(self, key):
        return SIZE.get(str(getattr(self, key)).lower(), 1.0)

    def colours(self):
        from .mesh import KITS
        k = KITS.get(self.kit.lower(), KITS["home"])
        skin = parse_colour(self.skin_tone, SKIN_TONES, SKIN_TONES["medium"])
        shoes_default = (0.06, 0.06, 0.07) if self.shoes != "trainers" else (0.92, 0.92, 0.92)
        return {
            "skin": skin,
            "shirt": parse_colour(self.top_colour, COLOURS, k["shirt"]),
            "shorts": parse_colour(self.bottom_colour, COLOURS, k["shorts"]),
            "socks": parse_colour(self.socks_colour, COLOURS, k["socks"]),
            "trim": parse_colour(self.trim_colour, COLOURS, k["trim"]),
            "boots": parse_colour(self.shoes_colour, COLOURS, shoes_default) if self.shoes != "barefoot" else skin,
            "hair": parse_colour(self.hair_colour, HAIR_COLOURS, HAIR_COLOURS["dark_brown"]),
            "eye": parse_colour(self.eye_colour, EYE_COLOURS, EYE_COLOURS["brown"]),
            "eye_white": (0.96, 0.96, 0.94),
            "mouth": tuple(c * 0.62 for c in skin[:1]) + (skin[1] * 0.38, skin[2] * 0.38),
            "ball": (0.95, 0.94, 0.9), "ball_seam": (0.78, 0.74, 0.68),
            "kart": parse_colour(self.extra.get("kart_colour", ""), COLOURS, k["shirt"]),
            "kart_dark": (0.09, 0.09, 0.1), "kart_trim": (0.82, 0.82, 0.86),
        }

    def to_dict(self):
        return asdict(self)


def load_spec(path) -> CharacterSpec:
    sp = CharacterSpec()
    known = set(CharacterSpec.__dataclass_fields__) - {"extra"}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = re.split(r"\s#\s|\s#$", line.rstrip("\n"), maxsplit=1)[0].strip()
            if not line or "=" not in line or line.startswith(("#", ";")):
                continue
            k, v = [x.strip() for x in line.split("=", 1)]
            k = k.lower().replace(" ", "_").replace("-", "_").replace("color", "colour")
            if k in known:
                f_type = CharacterSpec.__dataclass_fields__[k].type
                if f_type in ("float", float):
                    try:
                        v = float(v.split()[0])
                    except ValueError:
                        continue
                setattr(sp, k, v)
            else:
                sp.extra[k] = v
    return sp


