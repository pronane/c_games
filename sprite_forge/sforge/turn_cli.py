"""v8  forge.py turn : see a cut-out person from another angle (side / back) - from ONE front photo.

  forge.py turn CUTOUT_DIR|cutout.png [--turn 90|side|back|270] [--yaw DEG] [--depth auto|template|relief|side]
                [--side-photo IMG|VIDEO] [--side-faces right|left] [--template gender=1,age=0.55,...]
                [--out DIR] [--layers] [--pose-sheet]

Writes  turned_<yaw>.png         the rotated rest pose (transparent)
        compare_<yaw>.png        photo | turned, side by side, with what is real and what is estimated
        layers_<yaw>/<part>.png  one layer per body part (--layers)
        side_moves_<yaw>.png     every side-on fighter move, key frames (--pose-sheet)
        turn_report.txt

What is real and what is estimated: only the photographed FRONT is real.  Depth (how deep the body is
front-to-back) comes from the MakeHuman CC0 body template sliced at each photo row, or from a procedural
relief; a --side-photo of the same person replaces the estimated silhouette by the real one.  The back
and the far side are painted from the photo's own edge colours - nothing is generated by an AI model and
no new image of the person is invented."""
from __future__ import annotations
import argparse, json, os, time
from PIL import Image, ImageDraw, ImageFont


def _font(sz):
    for f in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "C:/Windows/Fonts/arialbd.ttf"):
        if os.path.isfile(f):
            return ImageFont.truetype(f, sz)
    return ImageFont.load_default()


def compare_image(cut, turned, yaw, depth, note=""):
    def fit(im, h):
        bb = im.getchannel("A").getbbox(); c = im.crop(bb)
        return c.resize((max(1, int(c.width * h / c.height)), h), Image.LANCZOS)
    h = 900
    a, b = fit(cut, h), fit(turned, h)
    foot = "front = real photo pixels; side / back / depth = ESTIMATED (%s)%s" % (depth, note)
    tw = int(max(_font(20).getlength(foot), 0)) + 80
    gap = max(40, int(_font(30).getlength("FRONT  (the photo)")) + 40 - a.width)   # keep the two titles apart
    W = max(a.width + b.width + 80 + gap, tw, a.width + gap + 40 + int(_font(30).getlength("TURNED %g deg" % yaw)) + 40)
    out = Image.new("RGB", (W, h + 150), (34, 36, 44))
    sq = 24
    bg = Image.new("RGB", (W, h + 150))
    d0 = ImageDraw.Draw(bg)
    for y in range(0, h + 150, sq):
        for x in range(0, W, sq):
            d0.rectangle([x, y, x + sq, y + sq], fill=(70, 72, 80) if (x // sq + y // sq) % 2 else (58, 60, 68))
    out.paste(bg)
    out.paste(a, (40, 90), a); out.paste(b, (40 + gap + a.width, 90), b)
    d = ImageDraw.Draw(out)
    d.text((40, 20), "FRONT  (the photo)", fill=(255, 255, 255), font=_font(30))
    d.text((40 + gap + a.width, 20), "TURNED %g deg" % yaw, fill=(255, 220, 120), font=_font(30))
    d.text((40, h + 100), foot,
           fill=(200, 200, 210), font=_font(20))
    return out


def main(argv):
    ap = argparse.ArgumentParser(prog="forge.py turn")
    ap.add_argument("src", help="cut-out folder from `forge.py cutout` (or its cutout.png)")
    ap.add_argument("--turn", default="90")
    ap.add_argument("--yaw", type=float)
    ap.add_argument("--depth", default="auto", choices=["auto", "template", "relief", "side"])
    ap.add_argument("--side-photo"); ap.add_argument("--side-faces", default="right", choices=["left", "right"])
    ap.add_argument("--side-frame", type=float, default=-1)
    ap.add_argument("--template", default="")
    ap.add_argument("--landmarks")
    ap.add_argument("--out")
    ap.add_argument("--layers", action="store_true")
    ap.add_argument("--pose-sheet", action="store_true")
    a = ap.parse_args(argv)
    from . import turn as TN
    src = a.src
    d = src if os.path.isdir(src) else os.path.dirname(os.path.abspath(src))
    cutp = os.path.join(src, "cutout.png") if os.path.isdir(src) else src
    lm = a.landmarks or os.path.join(d, "landmarks.json")
    if not (os.path.isfile(cutp) and os.path.isfile(lm)):
        print("turn: needs cutout.png + landmarks.json (run `forge.py cutout PHOTO --out DIR` first)"); return 2
    yaw = a.yaw if a.yaw is not None else TN.turn_args(a.turn)
    out = a.out or os.path.join(d, "turn")
    os.makedirs(out, exist_ok=True)
    cut = Image.open(cutp).convert("RGBA")
    L = json.load(open(lm))["landmarks"]
    oth = os.path.join(d, "others_mask.png")
    side = None
    if a.side_photo:
        from .build import BuildConfig, Report, _side_reference
        cfg = BuildConfig(); cfg.side_photo = a.side_photo; cfg.side_frame = a.side_frame
        rep = Report(print); side = _side_reference(cfg, rep)
    t0 = time.time()
    res = TN.build_turned(cut, L, yaw=yaw, depth=a.depth, side=side, side_faces=a.side_faces,
                          template_params=TN.parse_params(a.template),
                          others_mask=Image.open(oth) if os.path.isfile(oth) else None)
    import math
    if TN.is_side(yaw) and math.sin(math.radians(yaw)) < 0:
        TN.mirror_turned(res)
    dt = time.time() - t0
    tag = ("%g" % yaw).replace(".", "_")
    comp = res.composite
    bb = comp.getchannel("A").getbbox()
    comp.crop(bb).save(os.path.join(out, "turned_%s.png" % tag))
    compare_image(cut, comp, yaw, res.depth).save(os.path.join(out, "compare_%s.png" % tag))
    if a.layers:
        ld = os.path.join(out, "layers_%s" % tag); os.makedirs(ld, exist_ok=True)
        for k, im in res.layers.items():
            im.save(os.path.join(ld, k + ".png"))
    if a.pose_sheet:
        rig = TN.make_rig(res, L)
        from . import puppet as PP
        from .fighter_cli import EF_STATES
        n_ = {"walk": 10, "jump": 8, "bum_fireball": 8, "victory": 8, "crouch": 4, "idle": 5}
        rows = []
        for m in EF_STATES:
            keys, _ = TN.rig_move_keys(rig, m, n_.get(m, 6))
            rows.append((m, [rig.render(p) for p in (keys if len(keys) == n_.get(m, 6) else PP._sample(keys, n_.get(m, 6)))]))
        th = 220; cw = int(th * 0.8)
        sheet = Image.new("RGB", (140 + cw * 10, th * len(rows)), (200, 200, 210))
        dr = ImageDraw.Draw(sheet)
        for i, (m, fr) in enumerate(rows):
            dr.text((6, i * th + th // 2), m, fill=(20, 20, 30), font=_font(16))
            for j, im in enumerate(fr):
                c = im.crop((int(rig.cx - rig.stand_h * 0.55), rig.ground - int(rig.stand_h * 1.2), int(rig.cx + rig.stand_h * 0.55), rig.ground + 4))
                c.thumbnail((cw, th)); sheet.paste(c, (140 + j * cw, i * th), c)
        sheet.save(os.path.join(out, "side_moves_%s.png" % tag))
    with open(os.path.join(out, "turn_report.txt"), "w") as f:
        f.write("forge.py turn %s\nyaw %g deg, depth %s, %.1fs\n" % (" ".join(argv), yaw, res.depth, dt))
        f.write("near side after the turn: front-rig '%s'; %d px of another person's fingers removed from the hand\n" % (res.near, res.hand_removed))
        f.write("REAL: the photographed front.  ESTIMATED: body depth (%s), the side and back colours (photo edge colours),\n"
                "the hidden hand (copy of the visible one).  Nothing here is AI-generated.\n" % res.depth)
    print("turn: %g deg (%s) in %.1fs -> %s" % (yaw, res.depth, dt, out))
    return 0
